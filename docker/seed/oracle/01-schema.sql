CREATE VIEW order_totals AS
SELECT o.id AS order_id, o.customer_id, o.status, SUM(i.quantity * i.unit_price) AS total
FROM orders o
JOIN order_items i ON i.order_id = o.id
GROUP BY o.id, o.customer_id, o.status;

CREATE SEQUENCE invoice_number_seq START WITH 1000;

CREATE FUNCTION order_total(p_order_id IN NUMBER) RETURN NUMBER
AS
  v_total NUMBER(12, 2);
BEGIN
  SELECT NVL(SUM(quantity * unit_price), 0) INTO v_total FROM order_items WHERE order_id = p_order_id;
  RETURN v_total;
END;
/

CREATE PROCEDURE restock(p_product_id IN NUMBER, p_amount IN NUMBER)
AS
BEGIN
  UPDATE products SET stock = stock + p_amount WHERE id = p_product_id;
END;
/

CREATE TRIGGER order_items_quantity_check
BEFORE INSERT OR UPDATE ON order_items
FOR EACH ROW
BEGIN
  IF :NEW.quantity <= 0 THEN
    RAISE_APPLICATION_ERROR(-20001, 'quantity must be positive');
  END IF;
END;
/

