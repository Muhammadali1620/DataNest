CREATE TABLE customers (
  id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR2(255) NOT NULL UNIQUE,
  full_name NVARCHAR2(255),
  country CHAR(2),
  created_at TIMESTAMP(0) DEFAULT TIMESTAMP '2024-01-01 00:00:00' NOT NULL
);
COMMENT ON TABLE customers IS 'Shop customers';

CREATE TABLE products (
  id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku VARCHAR2(32) NOT NULL UNIQUE,
  name NVARCHAR2(255) NOT NULL,
  price NUMBER(10, 2) NOT NULL CHECK (price >= 0),
  stock NUMBER(10) DEFAULT 0 NOT NULL,
  is_active BOOLEAN DEFAULT TRUE NOT NULL,
  attributes JSON
);
CREATE INDEX ix_products_name ON products (name);
COMMENT ON COLUMN products.name IS 'What the shop calls it';

CREATE TABLE orders (
  id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id NUMBER(10) NOT NULL REFERENCES customers (id),
  status VARCHAR2(16) DEFAULT 'new' NOT NULL
    CHECK (status IN ('new', 'paid', 'shipped', 'cancelled')),
  ordered_at TIMESTAMP(0) NOT NULL,
  note NVARCHAR2(2000)
);
CREATE INDEX ix_orders_customer ON orders (customer_id);

CREATE TABLE order_items (
  order_id NUMBER(10) NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  product_id NUMBER(10) NOT NULL REFERENCES products (id),
  quantity NUMBER(10) NOT NULL,
  unit_price NUMBER(10, 2) NOT NULL,
  PRIMARY KEY (order_id, product_id)
);

