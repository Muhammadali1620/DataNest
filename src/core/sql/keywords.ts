/** Keywords of a driver, or the union when the connection is unknown. */
export function keywordsOf(driver?: DriverId): readonly string[] {
  if (driver !== undefined && isSqlDriver(driver)) {
    return KEYWORDS[driver];
  }
  return [
    ...new Set([
      ...MYSQL_KEYWORDS,
      ...POSTGRES_KEYWORDS,
      ...SQLITE_KEYWORDS,
      ...MSSQL_KEYWORDS,
      ...CLICKHOUSE_KEYWORDS,
      ...ORACLE_KEYWORDS,
    ]),
  ].sort();
}
