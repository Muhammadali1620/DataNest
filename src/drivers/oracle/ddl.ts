// Structure changes in Oracle. DDL commits by itself here, so an ALTER runs change by
// change; comments live outside CREATE TABLE; a schema is a user, which DataNest does not
// create or drop (that needs passwords and quotas).

import { DbError } from '../../core/errors';
import type { ObjectRef, RelationKind, TableRef } from '../../core/model/objects';
import {
  type ColumnDesign,
  composeType,
  type ForeignKeyDesign,
  type TableBackground,
  type TableDesign,
} from '../../shared/table-design';
import { diffTables, isEmptyDiff } from '../../shared/table-diff';
import { type AlterPlan, EMPTY_PLAN, type SchemaDdl } from '../driver';
import { columnList, createTableSql, foreignKeySql, primaryKeySql } from '../common/design-sql';
import { quoteIdentifier, quoteString, quoteTable } from './quote';
import { msg } from '../../core/user-message';

const TYPES = [
  'NUMBER',
  'INTEGER',
  'BINARY_DOUBLE',
  'BINARY_FLOAT',
  'VARCHAR2',
  'NVARCHAR2',
  'CHAR',
  'CLOB',
  'NCLOB',
  'DATE',
  'TIMESTAMP',
  'TIMESTAMP WITH TIME ZONE',
  'BOOLEAN',
  'JSON',
  'RAW',
  'BLOB',
];

const RELATION_WORDS: Readonly<Record<RelationKind, string>> = {
  table: 'TABLE',
  view: 'VIEW',
  'materialized-view': 'MATERIALIZED VIEW',
};

/** Oracle knows ON DELETE CASCADE and SET NULL only, and no ON UPDATE at all. */
export function oracleKey(key: ForeignKeyDesign): ForeignKeyDesign {
  const onDelete =
    key.onDelete === 'CASCADE' || key.onDelete === 'SET NULL' ? key.onDelete : 'NO ACTION';
  return { ...key, onDelete, onUpdate: 'NO ACTION' };
}

/** `"name" type [DEFAULT …|identity] [NOT NULL]`: Oracle wants the default before constraints. */
export function oracleColumnSql(column: ColumnDesign): string {
  const pieces = [quoteIdentifier(column.name.trim()), composeType(column.type, column.length)];
  if (column.autoIncrement) {
    pieces.push('GENERATED BY DEFAULT ON NULL AS IDENTITY');
  } else if (column.defaultValue.trim() !== '') {
    pieces.push(`DEFAULT ${column.defaultValue.trim()}`);
  }
  if ((!column.nullable || column.primaryKey) && !column.autoIncrement) {
    pieces.push('NOT NULL');
  }
  return pieces.join(' ');
}

function qualified(table: TableRef, name: string): string {
  return quoteTable({ ...(table.schema === undefined ? {} : { schema: table.schema }), name });
}

function comment(target: string, text: string): string {
  return `COMMENT ON ${target} IS ${quoteString(text)}`;
}

/** Index names belong to the schema: they are named with it. */
function indexSql(
  table: TableRef,
  design: TableDesign,
  index: TableDesign['indexes'][number],
  target: string,
): string {
  return `CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${qualified(table, index.name.trim())} ON ${target} ${columnList(design, index.columns, quoteIdentifier)}`;
}

/** `CREATE VIEW …` as `CREATE OR REPLACE VIEW …`, for views, routines and triggers. */
export function orReplace(sql: string): string {
  return sql.replace(
    /^(\s*)CREATE\s+(?!OR\s+REPLACE)((?:(?:NO)?FORCE\s+)?(?:EDITIONABLE\s+|NONEDITIONABLE\s+)?(?:VIEW|FUNCTION|PROCEDURE|TRIGGER)\b)/iu,
    '$1CREATE OR REPLACE $2',
  );
}

export const oracleDdl: SchemaDdl = {
  designer: {
    columnComments: true,
    tableComment: true,
    types: TYPES,
    reorder: false,
    autoIncrement: true,
    foreignKeys: true,
    uniqueIndexes: true,
  },
  createTable: (table, rawDesign) => {
    const design = { ...rawDesign, foreignKeys: rawDesign.foreignKeys.map(oracleKey) };
    const target = qualified(table, design.name.trim());
    const keys = design.foreignKeys.map((key) =>
      foreignKeySql(
        design,
        key,
        quoteIdentifier,
        qualified(
          { ...table, ...(key.targetSchema === undefined ? {} : { schema: key.targetSchema }) },
          key.targetTable.trim(),
        ),
      ),
    );
    return [
      createTableSql(target, [
        ...design.columns.map(oracleColumnSql),
        ...primaryKeySql(design, quoteIdentifier),
        ...keys,
      ]),
      ...design.indexes.map((index) => indexSql(table, design, index, target)),
      ...(design.comment === '' ? [] : [comment(`TABLE ${target}`, design.comment)]),
      ...design.columns
        .filter((column) => column.comment !== '')
        .map((column) =>
          comment(`COLUMN ${target}.${quoteIdentifier(column.name.trim())}`, column.comment),
        ),
    ];
  },
  alterTable: oracleAlterTable,
  dropRelation: (table, kind) =>
    `DROP ${RELATION_WORDS[kind]} ${quoteTable(table)}${kind === 'table' ? ' CASCADE CONSTRAINTS' : ''}`,
  renameRelation: (table, kind, newName) =>
    kind === 'table'
      ? `ALTER TABLE ${quoteTable(table)} RENAME TO ${quoteIdentifier(newName)}`
      : // RENAME reaches only the session's own schema; views have no ALTER … RENAME.
        `RENAME ${quoteIdentifier(table.name)} TO ${quoteIdentifier(newName)}`,
  truncateTable: (table) => `TRUNCATE TABLE ${quoteTable(table)}`,
  dropObject: (object: ObjectRef) => {
    switch (object.kind) {
      case 'table':
        return `DROP TABLE ${quoteTable(object)} CASCADE CONSTRAINTS`;
      case 'view':
        return `DROP ${object.materialized === true ? 'MATERIALIZED VIEW' : 'VIEW'} ${quoteTable(object)}`;
      case 'function':
      case 'procedure':
      case 'trigger':
      case 'sequence':
        return `DROP ${object.kind.toUpperCase()} ${quoteTable(object)}`;
      case 'event':
        throw new DbError(
          'unsupported',
          msg('Oracle keeps scheduled jobs apart, in DBMS_SCHEDULER'),
        );
    }
  },
  replaceObject: (object, statements, original) => {
    switch (object.kind) {
      case 'view':
      case 'function':
      case 'procedure':
      case 'trigger':
        break;
      case 'table':
      case 'sequence':
      case 'event':
        throw new DbError('unsupported', msg('A {0} is not edited as a definition', object.kind));
    }
    if (object.materialized === true) {
      // A materialized view cannot be replaced: it is dropped and made again, and made
      // as it was when the new one fails.
      return {
        check: [],
        statements: [`DROP MATERIALIZED VIEW ${quoteTable(object)}`, ...statements],
        recovery: [...original],
      };
    }
    // CREATE OR REPLACE swaps the object in one step. A routine that does not compile is
    // still stored, broken, so the old definition is put back the same way.
    return { check: [], statements: statements.map(orReplace), recovery: original.map(orReplace) };
  },
};

export function oracleAlterTable(
  table: TableRef,
  before: TableDesign,
  rawAfter: TableDesign,
  background: TableBackground,
): AlterPlan {
  const after = { ...rawAfter, foreignKeys: rawAfter.foreignKeys.map(oracleKey) };
  const diff = diffTables(before, after);
  if (isEmptyDiff(diff)) {
    return EMPTY_PLAN;
  }
  for (const change of diff.changed) {
    if (change.autoIncrement) {
      throw new DbError(
        'unsupported',
        msg(
          'Oracle cannot turn the existing column {0} into an identity column or back',
          change.after.name.trim(),
        ),
      );
    }
  }
  const target = quoteTable(table);
  const alter = (clause: string): string => `ALTER TABLE ${target} ${clause}`;
  const q = quoteIdentifier;
  const statements: string[] = [];

  for (const key of diff.droppedKeys) {
    statements.push(alter(`DROP CONSTRAINT ${q(key.original ?? key.name)}`));
  }
  for (const index of diff.droppedIndexes) {
    const name = index.original ?? index.name;
    statements.push(
      background.constraintIndexes.includes(name)
        ? alter(`DROP CONSTRAINT ${q(name)}`)
        : `DROP INDEX ${qualified(table, name)}`,
    );
  }
  if (diff.primaryKey && before.columns.some((column) => column.primaryKey)) {
    statements.push(alter('DROP PRIMARY KEY'));
  }
  for (const column of diff.dropped) {
    statements.push(alter(`DROP COLUMN ${q(column.original ?? column.name)}`));
  }
  for (const change of diff.changed) {
    const { before: old, after: next } = change;
    const name = q(next.name.trim());
    if (change.renamed) {
      statements.push(alter(`RENAME COLUMN ${q(old.original ?? old.name)} TO ${name}`));
    }
    if (change.type) {
      statements.push(alter(`MODIFY (${name} ${composeType(next.type, next.length)})`));
    }
    if (change.defaultValue) {
      statements.push(
        alter(
          `MODIFY (${name} DEFAULT ${next.defaultValue.trim() === '' ? 'NULL' : next.defaultValue.trim()})`,
        ),
      );
    }
    if (change.nullable) {
      // Oracle refuses to set what is already set, so only a real change is sent.
      statements.push(
        alter(`MODIFY (${name} ${next.nullable && !next.primaryKey ? 'NULL' : 'NOT NULL'})`),
      );
    }
  }
  for (const column of diff.added) {
    statements.push(alter(`ADD (${oracleColumnSql(column)})`));
  }
  const keyColumns = after.columns.filter((column) => column.primaryKey).map((c) => c.id);
  if (diff.primaryKey && keyColumns.length > 0) {
    statements.push(alter(`ADD PRIMARY KEY ${columnList(after, keyColumns, q)}`));
  }
  for (const index of diff.addedIndexes) {
    statements.push(indexSql(table, after, index, target));
  }
  for (const key of diff.addedKeys) {
    const keyTarget = qualified(
      { ...table, ...(key.targetSchema === undefined ? {} : { schema: key.targetSchema }) },
      key.targetTable.trim(),
    );
    statements.push(alter(`ADD ${foreignKeySql(after, key, q, keyTarget)}`));
  }
  if (diff.comment) {
    statements.push(comment(`TABLE ${target}`, after.comment));
  }
  const commented = [
    ...diff.changed.filter((change) => change.comment).map((change) => change.after),
    ...diff.added.filter((column) => column.comment !== ''),
  ];
  for (const column of commented) {
    statements.push(comment(`COLUMN ${target}.${q(column.name.trim())}`, column.comment));
  }
  if (diff.renamed) {
    statements.push(alter(`RENAME TO ${q(after.name.trim())}`));
  }
  return { statements, notes: diff.order ? ['order-ignored'] : [], recovery: [] };
}
