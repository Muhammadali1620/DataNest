// What an Oracle dump script looks like (V5.2). Every statement ends with a `/` line, as
// SQL*Plus expects for PL/SQL; several rows go in as one PL/SQL block of INSERTs (INSERT
// ALL would give every row of it the same identity value and takes 999 columns at most);
// drops are PL/SQL that forgives a missing object, as DROP … IF EXISTS is 23ai only.

import { DbError } from '../../core/errors';
import type { ObjectRef, RelationKind, TableRef } from '../../core/model/objects';
import type { DumpDialect } from '../driver';
import { quoteIdentifier, quoteString, quoteTable } from './quote';

/** Runs a DROP and ignores only the error that says the object is not there. */
export function dropIfExists(statement: string, missingCode: number): string {
  return [
    'BEGIN',
    `  EXECUTE IMMEDIATE ${quoteString(statement)};`,
    'EXCEPTION',
    `  WHEN OTHERS THEN IF SQLCODE <> -${missingCode} THEN RAISE; END IF;`,
    'END;',
  ].join('\n');
}

const MISSING: Readonly<Record<ObjectRef['kind'], number>> = {
  table: 942,
  view: 942,
  function: 4043,
  procedure: 4043,
  trigger: 4080,
  sequence: 2289,
  event: 0,
};

export const oracleDump: DumpDialect = {
  prepare: [],
  // Every table of the dump is read as of one moment.
  beginSnapshot: ['SET TRANSACTION READ ONLY'],
  endSnapshot: ['COMMIT'],
  header: [],
  footer: [],
  keysAfterData: true,
  // A schema is a user, made with a password and quotas, not by a script. What the script
  // needs is that names left unqualified in bodies (a trigger's ON table, a view's FROM)
  // mean the dumped schema, whoever runs it: Oracle reads them in the session's schema.
  createSchema: (name) => `ALTER SESSION SET CURRENT_SCHEMA = ${quoteIdentifier(name)}`,
  routinesFirst: false,
  insert: (quotedTable, quotedColumns, rows) => {
    const into = `INSERT INTO ${quotedTable} (${quotedColumns.join(', ')}) VALUES `;
    return rows.length === 1
      ? `${into}${rows[0] ?? ''}`
      : ['BEGIN', ...rows.map((row) => `  ${into}${row};`), 'END;'].join('\n');
  },
  // An identity column takes up numbering after the highest value inserted.
  resetSequence: (table: TableRef, column: string) =>
    `ALTER TABLE ${quoteTable(table)} MODIFY (${quoteIdentifier(column)} GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE))`,
  dropRelations: (tables: readonly TableRef[], kind: RelationKind) =>
    tables.map((table) =>
      kind === 'table'
        ? dropIfExists(`DROP TABLE ${quoteTable(table)} CASCADE CONSTRAINTS`, 942)
        : dropIfExists(
            `DROP ${kind === 'materialized-view' ? 'MATERIALIZED VIEW' : 'VIEW'} ${quoteTable(table)}`,
            kind === 'materialized-view' ? 12003 : 942,
          ),
    ),
  dropObject: (object: ObjectRef) => {
    if (object.kind === 'event') {
      throw new DbError('unsupported', 'Oracle keeps scheduled jobs apart, in DBMS_SCHEDULER');
    }
    const word =
      object.kind === 'view' && object.materialized === true
        ? 'MATERIALIZED VIEW'
        : object.kind.toUpperCase();
    // ORA-12003: no such materialized view.
    const missing =
      object.kind === 'view' && object.materialized === true ? 12003 : MISSING[object.kind];
    return dropIfExists(`DROP ${word} ${quoteTable(object)}`, missing);
  },
};
