// ALTER TABLE for PostgreSQL, one change per statement inside a transaction: either
// the whole design is applied or nothing is. Constraints the server removes on its
// own (with a dropped column) are dropped with IF EXISTS.

import type { TableRef } from '../../core/model/objects';
import { composeType, type TableBackground, type TableDesign } from '../../shared/table-design';
import { diffTables, isEmptyDiff } from '../../shared/table-diff';
import { type AlterPlan, EMPTY_PLAN } from '../driver';
import { columnList, columnSql, createIndexSql, foreignKeySql } from '../common/design-sql';
import { quoteIdentifier, quoteString, quoteTable } from './quote';

export function postgresAlterTable(
  table: TableRef,
  before: TableDesign,
  after: TableDesign,
  background: TableBackground,
): AlterPlan {
  const diff = diffTables(before, after);
  if (isEmptyDiff(diff)) {
    return EMPTY_PLAN;
  }
  const schema = table.schema === undefined ? {} : { schema: table.schema };
  const target = quoteTable({ ...schema, name: table.name });
  const alter = (clause: string): string => `ALTER TABLE ${target} ${clause}`;
  const q = quoteIdentifier;
  const statements: string[] = ['BEGIN'];

  for (const key of diff.droppedKeys) {
    statements.push(alter(`DROP CONSTRAINT IF EXISTS ${q(key.original ?? key.name)}`));
  }
  for (const index of diff.droppedIndexes) {
    const name = index.original ?? index.name;
    statements.push(
      background.constraintIndexes.includes(name)
        ? alter(`DROP CONSTRAINT IF EXISTS ${q(name)}`)
        : `DROP INDEX IF EXISTS ${quoteTable({ ...schema, name })}`,
    );
  }
  if (diff.primaryKey && before.columns.some((column) => column.primaryKey)) {
    const name = background.primaryKeyName ?? `${before.name.trim()}_pkey`;
    statements.push(alter(`DROP CONSTRAINT IF EXISTS ${q(name)}`));
  }
  for (const column of diff.dropped) {
    statements.push(alter(`DROP COLUMN ${q(column.original ?? column.name)}`));
  }
  for (const change of diff.changed) {
    const { before: old, after: next } = change;
    const name = q(next.name.trim());
    if (change.renamed) {
      statements.push(alter(`RENAME COLUMN ${q(old.original ?? old.name)} TO ${name}`));
    }
    if (change.autoIncrement && !next.autoIncrement) {
      statements.push(alter(`ALTER COLUMN ${name} DROP IDENTITY IF EXISTS`));
    }
    // A default of the old type cannot be cast along with the column, so it is taken
    // off first and put back (as designed) once the type has changed.
    const retype = change.type && old.defaultValue.trim() !== '';
    if (retype) {
      statements.push(alter(`ALTER COLUMN ${name} DROP DEFAULT`));
    }
    if (change.type) {
      // USING makes the server convert values instead of refusing a text → number change.
      const type = composeType(next.type, next.length);
      statements.push(alter(`ALTER COLUMN ${name} TYPE ${type} USING ${name}::${type}`));
    }
    if (retype) {
      if (next.defaultValue.trim() !== '') {
        statements.push(alter(`ALTER COLUMN ${name} SET DEFAULT ${next.defaultValue.trim()}`));
      }
    } else if (change.defaultValue) {
      statements.push(
        alter(
          next.defaultValue.trim() === ''
            ? `ALTER COLUMN ${name} DROP DEFAULT`
            : `ALTER COLUMN ${name} SET DEFAULT ${next.defaultValue.trim()}`,
        ),
      );
    }
    if (change.nullable) {
      statements.push(
        alter(`ALTER COLUMN ${name} ${next.nullable ? 'DROP NOT NULL' : 'SET NOT NULL'}`),
      );
    }
    if (change.autoIncrement && next.autoIncrement) {
      statements.push(alter(`ALTER COLUMN ${name} ADD GENERATED BY DEFAULT AS IDENTITY`));
    }
  }
  for (const column of diff.added) {
    statements.push(
      alter(
        `ADD COLUMN ${columnSql(column, {
          quote: q,
          autoIncrement: () => 'GENERATED BY DEFAULT AS IDENTITY',
          trailer: () => '',
        })}`,
      ),
    );
  }
  const keyColumns = after.columns.filter((column) => column.primaryKey).map((c) => c.id);
  if (diff.primaryKey && keyColumns.length > 0) {
    statements.push(alter(`ADD PRIMARY KEY ${columnList(after, keyColumns, q)}`));
  }
  for (const index of diff.addedIndexes) {
    statements.push(createIndexSql(after, index, q, target));
  }
  for (const key of diff.addedKeys) {
    const keyTarget = quoteTable({
      ...(key.targetSchema === undefined ? schema : { schema: key.targetSchema }),
      name: key.targetTable.trim(),
    });
    statements.push(alter(`ADD ${foreignKeySql(after, key, q, keyTarget)}`));
  }
  const comment = (text: string): string => (text === '' ? 'NULL' : quoteString(text));
  if (diff.comment) {
    statements.push(`COMMENT ON TABLE ${target} IS ${comment(after.comment)}`);
  }
  const commented = [
    ...diff.changed.filter((change) => change.comment).map((change) => change.after),
    ...diff.added.filter((column) => column.comment !== ''),
  ];
  for (const column of commented) {
    statements.push(
      `COMMENT ON COLUMN ${target}.${q(column.name.trim())} IS ${comment(column.comment)}`,
    );
  }
  if (diff.renamed) {
    statements.push(alter(`RENAME TO ${q(after.name.trim())}`));
  }
  statements.push('COMMIT');
  return {
    statements,
    notes: diff.order ? ['order-ignored'] : [],
    recovery: ['ROLLBACK'],
  };
}
