// Structure changes in PostgreSQL. Materialized views have DDL words of their own,
// and routines are dropped by signature because names may be overloaded.

import { DbError } from '../../core/errors';
import type { ObjectRef, RelationKind } from '../../core/model/objects';
import type { SchemaDdl } from '../driver';
import {
  columnSql,
  createIndexSql,
  createTableSql,
  foreignKeySql,
  primaryKeySql,
} from '../common/design-sql';
import { postgresAlterTable } from './alter';
import { quoteIdentifier, quoteString, quoteTable } from './quote';

const TYPES = [
  'integer',
  'bigint',
  'smallint',
  'numeric',
  'real',
  'double precision',
  'boolean',
  'char',
  'varchar',
  'text',
  'uuid',
  'json',
  'jsonb',
  'date',
  'time',
  'timestamp',
  'timestamp with time zone',
  'interval',
  'bytea',
  'inet',
  'text[]',
  'integer[]',
];

const RELATION_WORDS: Readonly<Record<RelationKind, string>> = {
  table: 'TABLE',
  view: 'VIEW',
  'materialized-view': 'MATERIALIZED VIEW',
};

function qualified(object: { schema?: string; name: string }): string {
  return quoteTable(
    object.schema === undefined
      ? { name: object.name }
      : { schema: object.schema, name: object.name },
  );
}

export const postgresDdl: SchemaDdl = {
  createDatabase: (name) => `CREATE DATABASE ${quoteIdentifier(name)}`,
  dropDatabase: (name) => `DROP DATABASE ${quoteIdentifier(name)}`,
  createSchema: (name) => `CREATE SCHEMA ${quoteIdentifier(name)}`,
  dropSchema: (name, cascade) => `DROP SCHEMA ${quoteIdentifier(name)}${cascade ? ' CASCADE' : ''}`,
  // Columns of an existing table keep their places: PostgreSQL cannot move them.
  designer: { columnComments: true, tableComment: true, types: TYPES, reorder: false },
  alterTable: postgresAlterTable,
  createTable: (table, design) => {
    const target = qualified({ ...table, name: design.name.trim() });
    const columns = design.columns.map((column) =>
      columnSql(column, {
        quote: quoteIdentifier,
        autoIncrement: () => 'GENERATED BY DEFAULT AS IDENTITY',
        trailer: () => '',
      }),
    );
    // PostgreSQL keeps comments outside CREATE TABLE.
    const comments = [
      ...(design.comment === ''
        ? []
        : [`COMMENT ON TABLE ${target} IS ${quoteString(design.comment)}`]),
      ...design.columns
        .filter((column) => column.comment !== '')
        .map(
          (column) =>
            `COMMENT ON COLUMN ${target}.${quoteIdentifier(column.name.trim())} IS ${quoteString(column.comment)}`,
        ),
    ];
    const keys = design.foreignKeys.map((key) =>
      foreignKeySql(
        design,
        key,
        quoteIdentifier,
        qualified({ schema: key.targetSchema ?? table.schema, name: key.targetTable.trim() }),
      ),
    );
    const indexes = design.indexes.map((index) =>
      createIndexSql(design, index, quoteIdentifier, target),
    );
    return [
      createTableSql(target, [...columns, ...primaryKeySql(design, quoteIdentifier), ...keys]),
      ...indexes,
      ...comments,
    ];
  },
  dropRelation: (table, kind) => `DROP ${RELATION_WORDS[kind]} ${qualified(table)}`,
  renameRelation: (table, kind, newName) =>
    `ALTER ${RELATION_WORDS[kind]} ${qualified(table)} RENAME TO ${quoteIdentifier(newName)}`,
  truncateTable: (table) => `TRUNCATE TABLE ${qualified(table)}`,
  dropObject: (object: ObjectRef) => {
    switch (object.kind) {
      case 'table':
      case 'view':
        return `DROP ${RELATION_WORDS[object.kind]} ${qualified(object)}`;
      case 'function':
      case 'procedure':
        // The signature is the server's own text (pg_get_function_identity_arguments).
        return `DROP ${object.kind.toUpperCase()} ${qualified(object)}(${object.signature ?? ''})`;
      case 'trigger':
        if (object.table === undefined) {
          throw new DbError('unsupported', `The table of trigger ${object.name} is unknown`);
        }
        return `DROP TRIGGER ${quoteIdentifier(object.name)} ON ${qualified({ ...object, name: object.table })}`;
      case 'sequence':
        return `DROP SEQUENCE ${qualified(object)}`;
      case 'event':
        throw new DbError('unsupported', 'PostgreSQL has no scheduled events');
    }
  },
};
