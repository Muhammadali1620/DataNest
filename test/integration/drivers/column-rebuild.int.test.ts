// The rebuild script that moves a column where PostgreSQL cannot (D113), run on the real
// server: the columns end up in the new order and everything the drop took is back —
// rows, identity and serial counters, keys of other tables, indexes, checks, triggers.

import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { splitStatements } from '../../../src/core/sql/split';
import type { Session } from '../../../src/drivers/driver';
import { driver } from '../../../src/drivers/postgres';
import { planColumnReorder } from '../../../src/services/column-reorder';
import type { ResolvedConnectionConfig } from '../../../src/shared/connection';
import { testDatabase } from '../../helpers/databases';
import { firstColumn, runAll } from '../../helpers/driver-run';

const SCHEMA = 'rebuild_order_test';
const TABLE = { schema: SCHEMA, name: 'orders' };

function config(): ResolvedConnectionConfig {
  const db = testDatabase('postgres');
  return {
    id: 'rebuild-postgres',
    name: 'rebuild',
    driver: 'postgres',
    host: db.host,
    port: db.port,
    user: db.user,
    password: db.password,
    database: db.database,
  };
}

async function columnsOf(session: Session): Promise<string[]> {
  const result = await runAll(
    session,
    `SELECT column_name FROM information_schema.columns WHERE table_schema = '${SCHEMA}' AND table_name = 'orders' ORDER BY ordinal_position`,
  );
  return firstColumn(result) as string[];
}

async function run(session: Session, sql: string): Promise<void> {
  for (const statement of splitStatements(sql, 'postgres')) {
    await runAll(session, statement.text);
  }
}

describe('PostgreSQL column move by a rebuild script', () => {
  let session: Session;

  beforeAll(async () => {
    session = await driver.openSession(config());
    await runAll(session, `DROP SCHEMA IF EXISTS ${SCHEMA} CASCADE`);
    await runAll(session, `CREATE SCHEMA ${SCHEMA}`);
    await run(
      session,
      `
      CREATE SEQUENCE ${SCHEMA}.orders_ticket_seq;
      CREATE TABLE ${SCHEMA}.users (id integer PRIMARY KEY);
      CREATE TABLE ${SCHEMA}.orders (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id integer REFERENCES ${SCHEMA}.users (id) ON DELETE CASCADE,
        code varchar(20) NOT NULL DEFAULT 'x',
        ticket integer DEFAULT nextval('${SCHEMA}.orders_ticket_seq'),
        note text,
        CONSTRAINT positive CHECK (ticket IS NULL OR ticket > 0)
      );
      ALTER SEQUENCE ${SCHEMA}.orders_ticket_seq OWNED BY ${SCHEMA}.orders.ticket;
      COMMENT ON COLUMN ${SCHEMA}.orders.code IS 'the code';
      CREATE INDEX idx_code ON ${SCHEMA}.orders (code);
      CREATE INDEX idx_lower_note ON ${SCHEMA}.orders (lower(note)) WHERE note <> '';
      CREATE TABLE ${SCHEMA}.items (
        id integer PRIMARY KEY,
        order_id integer CONSTRAINT items_order REFERENCES ${SCHEMA}.orders (id) ON DELETE CASCADE
      );
      CREATE FUNCTION ${SCHEMA}.touch() RETURNS trigger AS $$ BEGIN NEW.note := coalesce(NEW.note, 'auto'); RETURN NEW; END $$ LANGUAGE plpgsql;
      CREATE TRIGGER trg_touch BEFORE INSERT ON ${SCHEMA}.orders FOR EACH ROW EXECUTE FUNCTION ${SCHEMA}.touch();
      INSERT INTO ${SCHEMA}.users VALUES (1), (2);
      INSERT INTO ${SCHEMA}.orders (user_id, code, note) VALUES (1, 'a', 'one'), (2, 'b', NULL), (1, 'c', '');
      INSERT INTO ${SCHEMA}.items VALUES (1, 1), (2, 3);
      `,
    );
  });

  afterAll(async () => {
    await runAll(session, `DROP SCHEMA IF EXISTS ${SCHEMA} CASCADE`);
    await session.close();
  });

  it('moves a column up and keeps everything else', async () => {
    expect(await columnsOf(session)).toEqual(['id', 'user_id', 'code', 'ticket', 'note']);
    const before = await runAll(session, `SELECT * FROM ${SCHEMA}.orders ORDER BY id`);
    const plan = await planColumnReorder(session.metadata, driver, TABLE, 'code', 'up');
    expect(plan?.kind).toBe('script');
    if (plan?.kind !== 'script') {
      return;
    }
    await run(session, plan.sql);

    expect(await columnsOf(session)).toEqual(['id', 'code', 'user_id', 'ticket', 'note']);
    // The same rows (compared by column name, the order of columns changed).
    const after = await runAll(session, `SELECT * FROM ${SCHEMA}.orders ORDER BY id`);
    expect(after.rows).toHaveLength(before.rows.length);
    const named = (result: typeof after): Record<string, unknown>[] =>
      result.rows.map((row) =>
        Object.fromEntries(
          (result.columnSets[0] ?? []).map((column, at) => [column.name, row[at]]),
        ),
      );
    expect(named(after)).toEqual(named(before));

    // No backup table is left behind.
    const left = await runAll(
      session,
      `SELECT count(*) FROM information_schema.tables WHERE table_schema = '${SCHEMA}' AND table_name LIKE '%order_backup'`,
    );
    expect(Number(left.rows[0]?.[0])).toBe(0);
  });

  it('keeps the counters going', async () => {
    // Identity continues after the rows copied; the serial sequence went on from 4 (3 rows used 1–3).
    await runAll(session, `INSERT INTO ${SCHEMA}.orders (user_id, code) VALUES (1, 'd')`);
    await runAll(session, `INSERT INTO ${SCHEMA}.orders (user_id, code) VALUES (1, 'e')`);
    const ids = await runAll(session, `SELECT id FROM ${SCHEMA}.orders ORDER BY id`);
    expect(firstColumn(ids)).toEqual([1, 2, 3, 4, 5]);
    const tickets = await runAll(
      session,
      `SELECT ticket FROM ${SCHEMA}.orders WHERE code IN ('d','e') ORDER BY id`,
    );
    expect(firstColumn(tickets)).toEqual([4, 5]);
    // The sequence still belongs to the column, so it goes with the table.
    const owner = await runAll(
      session,
      `SELECT d.refobjsubid FROM pg_depend d JOIN pg_class s ON s.oid = d.objid WHERE s.relname = 'orders_ticket_seq' AND d.deptype = 'a'`,
    );
    expect(owner.rows).toHaveLength(1);
  });

  it('keeps keys, indexes, checks, comments and the trigger', async () => {
    // A key of another table still works, in both directions.
    await expect(runAll(session, `INSERT INTO ${SCHEMA}.items VALUES (9, 999)`)).rejects.toThrow();
    await runAll(session, `DELETE FROM ${SCHEMA}.orders WHERE id = 1`);
    const items = await runAll(session, `SELECT id FROM ${SCHEMA}.items ORDER BY id`);
    expect(firstColumn(items)).toEqual([2]);
    // Own key, index with an expression and a condition, check, comment, trigger.
    await expect(
      runAll(session, `INSERT INTO ${SCHEMA}.orders (user_id, code) VALUES (77, 'z')`),
    ).rejects.toThrow();
    await expect(
      runAll(session, `INSERT INTO ${SCHEMA}.orders (user_id, code, ticket) VALUES (1, 'z', -5)`),
    ).rejects.toThrow();
    const indexes = await runAll(
      session,
      `SELECT indexname FROM pg_indexes WHERE schemaname = '${SCHEMA}' AND tablename = 'orders' ORDER BY 1`,
    );
    expect(firstColumn(indexes)).toEqual(['idx_code', 'idx_lower_note', 'orders_pkey']);
    const note = await runAll(session, `SELECT note FROM ${SCHEMA}.orders WHERE code = 'd'`);
    expect(firstColumn(note)).toEqual(['auto']);
    const comment = await runAll(
      session,
      `SELECT col_description('${SCHEMA}.orders'::regclass, 2)`,
    );
    expect(firstColumn(comment)).toEqual(['the code']);
  });

  it('moves a column down, and says nothing to do at the edges', async () => {
    const plan = await planColumnReorder(session.metadata, driver, TABLE, 'id', 'down');
    expect(plan?.kind).toBe('script');
    if (plan?.kind === 'script') {
      await run(session, plan.sql);
    }
    expect(await columnsOf(session)).toEqual(['code', 'id', 'user_id', 'ticket', 'note']);
    expect(await planColumnReorder(session.metadata, driver, TABLE, 'code', 'up')).toBeUndefined();
  });

  it('leaves the table as it was when a step fails (one transaction)', async () => {
    const before = await columnsOf(session);
    const plan = await planColumnReorder(session.metadata, driver, TABLE, 'note', 'up');
    expect(plan?.kind).toBe('script');
    if (plan?.kind !== 'script') {
      return;
    }
    // A view over the table makes the DROP fail half way.
    await runAll(session, `CREATE VIEW ${SCHEMA}.v AS SELECT id FROM ${SCHEMA}.orders`);
    try {
      await expect(run(session, plan.sql)).rejects.toThrow();
      await runAll(session, 'ROLLBACK').catch(() => undefined);
      expect(await columnsOf(session)).toEqual(before);
      const rows = await runAll(session, `SELECT count(*) FROM ${SCHEMA}.orders`);
      expect(Number(rows.rows[0]?.[0])).toBe(4);
      const keys = await runAll(
        session,
        `SELECT count(*) FROM pg_constraint WHERE conname = 'items_order'`,
      );
      expect(Number(keys.rows[0]?.[0])).toBe(1);
    } finally {
      await runAll(session, `DROP VIEW IF EXISTS ${SCHEMA}.v`);
    }
  });
});
