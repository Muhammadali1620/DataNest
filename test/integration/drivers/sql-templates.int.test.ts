// Templates for a real table run once their tab stops are filled in: what INSERT
// writes, SELECT reads back, UPDATE changes and DELETE removes.

import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import type { TableRef } from '../../../src/core/model/objects';
import type { Driver, Session } from '../../../src/drivers/driver';
import { driver as mysqlDriver } from '../../../src/drivers/mysql';
import { driver as postgresDriver } from '../../../src/drivers/postgres';
import { createSqliteDriver } from '../../../src/drivers/sqlite';
import { sqlTemplate, type TemplateKind } from '../../../src/services/sql-templates';
import type { DriverId, ResolvedConnectionConfig } from '../../../src/shared/connection';
import { templateColumns } from '../../../src/vscode/tree/template-commands';
import { testDatabase, type TestDatabaseId } from '../../helpers/databases';
import { runAll } from '../../helpers/driver-run';
import { buildSqliteWorker, type BuiltWorker } from '../../helpers/sqlite-worker';

/** Fills `${n:name}` the way a user would, from a map of column → SQL value. */
function fill(snippet: string, values: Record<string, string>): string {
  return snippet.replace(/\$\{\d+:([^}]*)\}/g, (_all, name: string) => values[name] ?? 'NULL');
}

async function check(session: Session, driver: Driver, table: TableRef): Promise<void> {
  const columns = await templateColumns(session.metadata, table);
  const template = (kind: TemplateKind) => sqlTemplate(kind, table, columns, driver.dialect);
  const run = async (sql: string) => (await runAll(session, sql.replace(/;$/, ''))).rows;

  await run(fill(template('insert'), { label: "'first'", qty: '2' }));
  const rows = await run(template('select'));
  expect(rows).toHaveLength(1);
  // Every table here numbers its rows with small integers.
  const id = Number(rows[0]?.[0]).toString();
  await run(fill(template('update'), { label: "'second'", qty: '5', id }));
  expect(await run(template('select'))).toEqual([[Number(id), 'second', 5]]);
  await run(fill(template('delete'), { id }));
  expect(await run(template('select'))).toEqual([]);
}

function config(id: TestDatabaseId, driver: DriverId): ResolvedConnectionConfig {
  const db = testDatabase(id);
  return {
    id: `tpl-${id}`,
    name: id,
    driver,
    host: db.host,
    port: db.port,
    user: db.user,
    password: db.password,
    database: db.database,
  };
}

describe.each([
  ['mysql', 'mysql', 'id INT AUTO_INCREMENT PRIMARY KEY, label VARCHAR(20), qty INT'],
  ['mariadb', 'mysql', 'id INT AUTO_INCREMENT PRIMARY KEY, label VARCHAR(20), qty INT'],
  [
    'postgres',
    'postgres',
    'id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label text, qty integer',
  ],
] as const)('templates on %s', (id, driverId, columns) => {
  let session: Session;
  const driver = driverId === 'mysql' ? mysqlDriver : postgresDriver;

  beforeAll(async () => {
    session = await driver.openSession(config(id, driverId));
    await runAll(session, 'DROP TABLE IF EXISTS tpl_probe');
    await runAll(session, `CREATE TABLE tpl_probe (${columns})`);
  });

  afterAll(async () => {
    await runAll(session, 'DROP TABLE IF EXISTS tpl_probe');
    await session.close();
  });

  it('inserts, selects, updates and deletes through the filled templates', async () => {
    await check(
      session,
      driver,
      driverId === 'mysql'
        ? { database: testDatabase(id).database, name: 'tpl_probe' }
        : { schema: 'public', name: 'tpl_probe' },
    );
  });
});

describe('templates on sqlite', () => {
  let worker: BuiltWorker;
  let dir: string;
  let driver: Driver;
  let session: Session;

  beforeAll(async () => {
    worker = await buildSqliteWorker();
    driver = createSqliteDriver({ workerPath: worker.workerPath });
    dir = mkdtempSync(join(tmpdir(), 'datanest-tpl-'));
    session = await driver.openSession({
      id: 'tpl-sqlite',
      name: 'sqlite',
      driver: 'sqlite',
      file: join(dir, 'tpl.db'),
    });
    await runAll(
      session,
      'CREATE TABLE tpl_probe (id INTEGER PRIMARY KEY AUTOINCREMENT, label TEXT, qty INTEGER)',
    );
  }, 60_000);

  afterAll(async () => {
    await session.close();
    rmSync(dir, { recursive: true, force: true });
    worker.dispose();
  });

  it('inserts, selects, updates and deletes through the filled templates', async () => {
    await check(session, driver, { name: 'tpl_probe' });
  });
});
