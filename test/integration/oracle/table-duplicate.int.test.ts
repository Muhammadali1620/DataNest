// "Duplicate Table…" (V10.2.3) on Oracle: an identity column, an index and a key to
// itself, names in upper case; the checks are in helpers/duplicate-suite.ts.

import { driver as oracleDriver } from '../../../src/drivers/oracle';
import { ORACLE_SERVICE, testDatabase } from '../../helpers/databases';
import { duplicateSuite } from '../../helpers/duplicate-suite';

duplicateSuite({
  label: 'oracle',
  driver: () => oracleDriver,
  config: () => {
    const db = testDatabase('oracle');
    return {
      id: 'dup-oracle',
      name: 'oracle',
      driver: 'oracle',
      host: db.host,
      port: db.port,
      user: db.user,
      password: db.password,
      database: ORACLE_SERVICE,
    };
  },
  scope: { schema: 'DATANEST' },
  create: [
    `CREATE TABLE staff (
       id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
       name VARCHAR2(50) NOT NULL,
       boss NUMBER REFERENCES staff (id))`,
    'CREATE INDEX staff_name_idx ON staff (name)',
    "INSERT INTO staff (name, boss) VALUES ('Ann', NULL)",
    "INSERT INTO staff (name, boss) VALUES ('Bob', 1)",
    "INSERT INTO staff (name, boss) VALUES ('Cy', 1)",
  ],
  drop: (table) => [`DROP TABLE IF EXISTS ${table} PURGE`],
  name: (table) => table,
  reported: (table) => table.toUpperCase(),
  keys: true,
});
