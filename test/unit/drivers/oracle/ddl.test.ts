describe('oracle createTable', () => {
  it('creates the table with its key, foreign key and index named with the schema', () => {
    expect(oracleDdl.createTable(table, before)).toEqual([
      [
        `CREATE TABLE ${target} (`,
        '  "id" int NOT NULL,',
        '  "customer_id" int,',
        '  "note" varchar(40),',
        '  PRIMARY KEY ("id"),',
        '  CONSTRAINT "fk_customer" FOREIGN KEY ("customer_id") REFERENCES "APP"."customers" ("id")',
        ')',
      ].join('\n'),
      `CREATE INDEX "APP"."ix_note" ON ${target} ("note")`,
    ]);
  });

  it('writes a table without a schema unqualified, unique indexes too', () => {
    const design = ordersDesign({
      foreignKeys: [],
      indexes: [{ id: 'i1', name: 'ux_note', columns: ['note'], unique: true }],
    });
    const sql = oracleDdl.createTable({ name: 'orders' }, design);
    expect(sql[0]).toMatch(/^CREATE TABLE "orders" \(/u);
    expect(sql[1]).toBe('CREATE UNIQUE INDEX "ux_note" ON "orders" ("note")');
  });

  it('creates an identity column and defaults', () => {
    const design: TableDesign = {
      name: 'events',
      comment: '',
      columns: [
        column('id', { type: 'NUMBER', autoIncrement: true, primaryKey: true, nullable: false }),
        column('at', { type: 'TIMESTAMP', defaultValue: 'SYSTIMESTAMP', nullable: false }),
      ],
      indexes: [],
      foreignKeys: [],
    };
    expect(oracleDdl.createTable(table, design)).toEqual([
      [
        'CREATE TABLE "APP"."events" (',
        '  "id" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,',
        '  "at" TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,',
        '  PRIMARY KEY ("id")',
        ')',
      ].join('\n'),
    ]);
  });

  it('writes only the delete rules Oracle knows and never ON UPDATE', () => {
    const rules = (onDelete: ForeignKeyDesign['onDelete']) =>
      oracleDdl.createTable(
        table,
        ordersDesign({ indexes: [], foreignKeys: [key({ onDelete, onUpdate: 'CASCADE' })] }),
      )[0];
    expect(rules('CASCADE')).toContain('REFERENCES "APP"."customers" ("id") ON DELETE CASCADE\n');
    expect(rules('SET NULL')).toContain('REFERENCES "APP"."customers" ("id") ON DELETE SET NULL\n');
    for (const onDelete of ['RESTRICT', 'SET DEFAULT', 'NO ACTION'] as const) {
      expect(rules(onDelete)).toContain('REFERENCES "APP"."customers" ("id")\n');
    }
    expect(rules('CASCADE')).not.toContain('ON UPDATE');
  });

  it('points a foreign key at the schema it names', () => {
    const sql = oracleDdl.createTable(
      table,
      ordersDesign({
        indexes: [],
        foreignKeys: [key({ targetSchema: 'SALES', targetTable: ' c ' })],
      }),
    )[0];
    expect(sql).toContain('REFERENCES "SALES"."c" ("id")');
  });

  it('adds the table and column comments after the table, quotes doubled', () => {
    const design = ordersDesign({
      comment: "Customer's orders",
      foreignKeys: [],
      indexes: [],
      columns: [column('id', { primaryKey: true, comment: 'Number' }), column('note')],
    });
    expect(oracleDdl.createTable(table, design).slice(1)).toEqual([
      `COMMENT ON TABLE ${target} IS 'Customer''s orders'`,
      `COMMENT ON COLUMN ${target}."id" IS 'Number'`,
    ]);
  });

  it('writes a comment outside ASCII as N…', () => {
    const design = ordersDesign({ comment: 'Заказы', foreignKeys: [], indexes: [] });
    expect(oracleDdl.createTable(table, design).at(-1)).toBe(
      `COMMENT ON TABLE ${target} IS N'Заказы'`,
    );
  });
});

describe('oracle alterTable', () => {
  it('returns the empty plan for an unchanged table', () => {
    expect(alter(structuredClone(before))).toBe(EMPTY_PLAN);
  });

  it('ignores a change of ON UPDATE, which Oracle does not keep', () => {
    const after = ordersDesign({
      foreignKeys: before.foreignKeys.map((k) => ({ ...k, onUpdate: 'CASCADE' as const })),
    });
    expect(alter(after)).toBe(EMPTY_PLAN);
  });

  it('renames a column', () => {
    expect(statements(withColumn(before, 'note', { name: 'memo' }))).toEqual([
      `ALTER TABLE ${target} RENAME COLUMN "note" TO "memo"`,
    ]);
  });

  it('changes a type with MODIFY', () => {
    expect(statements(withColumn(before, 'note', { type: 'VARCHAR2', length: '80' }))).toEqual([
      `ALTER TABLE ${target} MODIFY ("note" VARCHAR2(80))`,
    ]);
  });

  it('sets a default, and sets it to NULL when it is cleared', () => {
    expect(statements(withColumn(before, 'note', { defaultValue: " 'x' " }))).toEqual([
      `ALTER TABLE ${target} MODIFY ("note" DEFAULT 'x')`,
    ]);
    const withDefault = withColumn(before, 'note', { defaultValue: "'x'" });
    expect(statements(before, NO_BACKGROUND, withDefault)).toEqual([
      `ALTER TABLE ${target} MODIFY ("note" DEFAULT NULL)`,
    ]);
  });

  it('changes nullability only when it changed', () => {
    expect(statements(withColumn(before, 'customer_id', { nullable: false }))).toEqual([
      `ALTER TABLE ${target} MODIFY ("customer_id" NOT NULL)`,
    ]);
    const required = withColumn(before, 'customer_id', { nullable: false });
    expect(statements(before, NO_BACKGROUND, required)).toEqual([
      `ALTER TABLE ${target} MODIFY ("customer_id" NULL)`,
    ]);
  });

  it('renames before it modifies, under the new name', () => {
    expect(
      statements(withColumn(before, 'note', { name: 'memo', type: 'CLOB', length: '' })),
    ).toEqual([
      `ALTER TABLE ${target} RENAME COLUMN "note" TO "memo"`,
      `ALTER TABLE ${target} MODIFY ("memo" CLOB)`,
    ]);
  });

  it('adds a column with its comment', () => {
    const after = {
      ...before,
      columns: [
        ...before.columns,
        added('total', { type: 'NUMBER', length: '10,2', defaultValue: '0', comment: 'Sum' }),
      ],
    };
    expect(statements(after)).toEqual([
      `ALTER TABLE ${target} ADD ("total" NUMBER(10,2) DEFAULT 0)`,
      `COMMENT ON COLUMN ${target}."total" IS 'Sum'`,
    ]);
  });

  it('adds an identity column', () => {
    const after = {
      ...before,
      columns: [...before.columns, added('seq', { type: 'NUMBER', autoIncrement: true })],
    };
    expect(statements(after)).toEqual([
      `ALTER TABLE ${target} ADD ("seq" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY)`,
    ]);
  });

  it('drops a foreign key before the column it uses', () => {
    const after = ordersDesign({
      columns: before.columns.filter((c) => c.name !== 'customer_id'),
      foreignKeys: [],
    });
    expect(statements(after)).toEqual([
      `ALTER TABLE ${target} DROP CONSTRAINT "fk_customer"`,
      `ALTER TABLE ${target} DROP COLUMN "customer_id"`,
    ]);
  });

  it('drops an index by its schema-qualified name', () => {
    expect(statements(ordersDesign({ indexes: [] }))).toEqual(['DROP INDEX "APP"."ix_note"']);
    expect(
      oracleAlterTable({ name: 'orders' }, before, ordersDesign({ indexes: [] }), NO_BACKGROUND)
        .statements,
    ).toEqual(['DROP INDEX "ix_note"']);
  });

  it('drops the constraint behind a unique key instead of its index', () => {
    const background = { ...NO_BACKGROUND, constraintIndexes: ['ix_note'] };
    expect(statements(ordersDesign({ indexes: [] }), background)).toEqual([
      `ALTER TABLE ${target} DROP CONSTRAINT "ix_note"`,
    ]);
  });

  it('renames an index by dropping the old one and creating the new one', () => {
    const after = ordersDesign({
      indexes: [
        { id: 'i1', original: 'ix_note', name: 'ix_memo', columns: ['note'], unique: true },
      ],
    });
    expect(statements(after)).toEqual([
      'DROP INDEX "APP"."ix_note"',
      `CREATE UNIQUE INDEX "APP"."ix_memo" ON ${target} ("note")`,
    ]);
  });

  it('replaces the primary key: drop first, add last', () => {
    const after = withColumn(before, 'customer_id', { primaryKey: true });
    expect(statements(after)).toEqual([
      `ALTER TABLE ${target} DROP PRIMARY KEY`,
      `ALTER TABLE ${target} ADD PRIMARY KEY ("id", "customer_id")`,
    ]);
  });

  it('adds a primary key to a table without one, and drops one that goes', () => {
    const keyless = withColumn(before, 'id', { primaryKey: false });
    expect(statements(before, NO_BACKGROUND, keyless)).toEqual([
      `ALTER TABLE ${target} ADD PRIMARY KEY ("id")`,
    ]);
    expect(statements(keyless)).toEqual([`ALTER TABLE ${target} DROP PRIMARY KEY`]);
  });

  it('adds a foreign key with the delete rule Oracle knows, in the named schema', () => {
    const after = ordersDesign({
      foreignKeys: [
        ...before.foreignKeys,
        key({ targetSchema: 'SALES', onDelete: 'RESTRICT', onUpdate: 'CASCADE' }),
        key({ id: 'k3', name: 'fk_y', onDelete: 'CASCADE' }),
      ],
    });
    expect(statements(after)).toEqual([
      `ALTER TABLE ${target} ADD CONSTRAINT "fk_x" FOREIGN KEY ("customer_id") REFERENCES "SALES"."customers" ("id")`,
      `ALTER TABLE ${target} ADD CONSTRAINT "fk_y" FOREIGN KEY ("customer_id") REFERENCES "APP"."customers" ("id") ON DELETE CASCADE`,
    ]);
  });

  it('comments on the table and changed columns, also to clear a comment', () => {
    expect(statements({ ...before, comment: 'Orders' })).toEqual([
      `COMMENT ON TABLE ${target} IS 'Orders'`,
    ]);
    expect(statements(withColumn(before, 'note', { comment: "it's" }))).toEqual([
      `COMMENT ON COLUMN ${target}."note" IS 'it''s'`,
    ]);
    const commented = withColumn(before, 'note', { comment: 'x' });
    expect(statements(before, NO_BACKGROUND, commented)).toEqual([
      `COMMENT ON COLUMN ${target}."note" IS ''`,
    ]);
  });

  it('renames the table last', () => {
    expect(statements({ ...before, name: ' orders2 ', comment: 'c' })).toEqual([
      `COMMENT ON TABLE ${target} IS 'c'`,
      `ALTER TABLE ${target} RENAME TO "orders2"`,
    ]);
  });

  it('puts every kind of change in a safe order', () => {
    const after: TableDesign = {
      name: 'orders2',
      comment: 'All',
      columns: [
        column('id', { primaryKey: true, nullable: false }),
        column('customer_id', { primaryKey: true, nullable: false }),
        column('note', { name: 'memo', type: 'VARCHAR2', length: '80' }),
        added('total', { comment: 'Sum' }),
      ],
      indexes: [{ id: 'i2', name: 'ix_memo', columns: ['note'], unique: false }],
      foreignKeys: [key()],
    };
    expect(statements(after)).toEqual([
      `ALTER TABLE ${target} DROP CONSTRAINT "fk_customer"`,
      'DROP INDEX "APP"."ix_note"',
      `ALTER TABLE ${target} DROP PRIMARY KEY`,
      `ALTER TABLE ${target} MODIFY ("customer_id" NOT NULL)`,
      `ALTER TABLE ${target} RENAME COLUMN "note" TO "memo"`,
      `ALTER TABLE ${target} MODIFY ("memo" VARCHAR2(80))`,
      `ALTER TABLE ${target} ADD ("total" int)`,
      `ALTER TABLE ${target} ADD PRIMARY KEY ("id", "customer_id")`,
      `CREATE INDEX "APP"."ix_memo" ON ${target} ("memo")`,
      `ALTER TABLE ${target} ADD CONSTRAINT "fk_x" FOREIGN KEY ("customer_id") REFERENCES "APP"."customers" ("id")`,
      `COMMENT ON TABLE ${target} IS 'All'`,
      `COMMENT ON COLUMN ${target}."total" IS 'Sum'`,
      `ALTER TABLE ${target} RENAME TO "orders2"`,
    ]);
  });

  it('keeps the column order and says so', () => {
    const [id, customer, note] = before.columns;
    if (id === undefined || customer === undefined || note === undefined) {
      throw new Error('ordersDesign has three columns');
    }
    const plan = alter({ ...before, columns: [note, id, customer] });
    expect(plan).toEqual({ statements: [], notes: ['order-ignored'], recovery: [] });
  });

  it('says nothing about order when it stays', () => {
    expect(alter({ ...before, comment: 'x' }).notes).toEqual([]);
    expect(alter({ ...before, comment: 'x' }).recovery).toEqual([]);
  });

  it('refuses to turn a column into an identity column or back', () => {
    const toIdentity = withColumn(before, 'id', { autoIncrement: true });
    expect(() => alter(toIdentity)).toThrow(DbError);
    expect(() => alter(toIdentity)).toThrow(
      expect.objectContaining({
        code: 'unsupported',
        message: expect.stringContaining('id') as unknown,
      }),
    );
    expect(() => alter(before, NO_BACKGROUND, toIdentity)).toThrow(
      expect.objectContaining({ code: 'unsupported' }),
    );
  });
});

