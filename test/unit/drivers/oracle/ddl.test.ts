describe('oracle dropObject', () => {
  const drop = (object: ObjectRef) => oracleDdl.dropObject(object);

  it('drops each kind with its own words', () => {
    expect(drop({ kind: 'table', schema: 'APP', name: 'T' })).toBe(
      'DROP TABLE "APP"."T" CASCADE CONSTRAINTS',
    );
    expect(drop({ kind: 'view', schema: 'APP', name: 'V' })).toBe('DROP VIEW "APP"."V"');
    expect(drop({ kind: 'view', name: 'M', materialized: true })).toBe(
      'DROP MATERIALIZED VIEW "M"',
    );
    expect(drop({ kind: 'function', schema: 'APP', name: 'F' })).toBe('DROP FUNCTION "APP"."F"');
    expect(drop({ kind: 'procedure', name: 'P' })).toBe('DROP PROCEDURE "P"');
    expect(drop({ kind: 'trigger', schema: 'APP', name: 'TR', table: 'T' })).toBe(
      'DROP TRIGGER "APP"."TR"',
    );
    expect(drop({ kind: 'sequence', schema: 'APP', name: 'S' })).toBe('DROP SEQUENCE "APP"."S"');
  });

  it('refuses events, which Oracle keeps in its scheduler', () => {
    expect(() => drop({ kind: 'event', name: 'E' })).toThrow(
      expect.objectContaining({ code: 'unsupported' }),
    );
  });
});

describe('orReplace', () => {
  it('turns CREATE of a view, routine or trigger into CREATE OR REPLACE', () => {
    expect(orReplace('CREATE VIEW v AS SELECT 1 FROM dual')).toBe(
      'CREATE OR REPLACE VIEW v AS SELECT 1 FROM dual',
    );
    expect(orReplace('CREATE FUNCTION f RETURN NUMBER IS BEGIN RETURN 1; END;')).toBe(
      'CREATE OR REPLACE FUNCTION f RETURN NUMBER IS BEGIN RETURN 1; END;',
    );
    expect(orReplace('CREATE PROCEDURE p IS BEGIN NULL; END;')).toBe(
      'CREATE OR REPLACE PROCEDURE p IS BEGIN NULL; END;',
    );
    expect(orReplace('CREATE TRIGGER t BEFORE INSERT ON x BEGIN NULL; END;')).toBe(
      'CREATE OR REPLACE TRIGGER t BEFORE INSERT ON x BEGIN NULL; END;',
    );
  });

  it('keeps FORCE, NOFORCE, EDITIONABLE and NONEDITIONABLE', () => {
    expect(orReplace('CREATE FORCE VIEW v AS SELECT 1 FROM dual')).toBe(
      'CREATE OR REPLACE FORCE VIEW v AS SELECT 1 FROM dual',
    );
    expect(orReplace('CREATE NOFORCE VIEW v AS SELECT 1 FROM dual')).toBe(
      'CREATE OR REPLACE NOFORCE VIEW v AS SELECT 1 FROM dual',
    );
    expect(orReplace('CREATE FORCE EDITIONABLE VIEW v AS SELECT 1 FROM dual')).toBe(
      'CREATE OR REPLACE FORCE EDITIONABLE VIEW v AS SELECT 1 FROM dual',
    );
    expect(orReplace('CREATE EDITIONABLE FUNCTION f RETURN NUMBER IS BEGIN RETURN 1; END;')).toBe(
      'CREATE OR REPLACE EDITIONABLE FUNCTION f RETURN NUMBER IS BEGIN RETURN 1; END;',
    );
    expect(orReplace('CREATE NONEDITIONABLE PROCEDURE p IS BEGIN NULL; END;')).toBe(
      'CREATE OR REPLACE NONEDITIONABLE PROCEDURE p IS BEGIN NULL; END;',
    );
  });

  it('keeps leading blanks and the case of the rest', () => {
    expect(orReplace('\n  create editionable trigger t before insert on x begin null; end;')).toBe(
      '\n  CREATE OR REPLACE editionable trigger t before insert on x begin null; end;',
    );
    expect(orReplace('Create\tView v as select 1 from dual')).toBe(
      'CREATE OR REPLACE View v as select 1 from dual',
    );
  });

  it('leaves CREATE OR REPLACE, tables and anything else alone', () => {
    for (const sql of [
      'CREATE OR REPLACE TRIGGER t BEFORE INSERT ON x BEGIN NULL; END;',
      'create  or   replace view v as select 1 from dual',
      'CREATE OR REPLACE FORCE EDITIONABLE VIEW v AS SELECT 1 FROM dual',
      'CREATE TABLE t (a NUMBER)',
      'CREATE INDEX i ON t (a)',
      'CREATE MATERIALIZED VIEW m AS SELECT 1 FROM dual',
      'CREATE VIEWS_TABLE x',
      'ALTER TRIGGER t ENABLE',
      'SELECT 1 FROM dual',
      '',
    ]) {
      expect(orReplace(sql)).toBe(sql);
    }
  });
});

describe('oracle replaceObject', () => {
  const view: ObjectRef = { kind: 'view', schema: 'APP', name: 'V' };

  it('replaces with CREATE OR REPLACE and recovers the original the same way', () => {
    const plan = oracleDdl.replaceObject(
      view,
      ['CREATE VIEW "APP"."V" AS SELECT 2 FROM dual'],
      ['CREATE FORCE EDITIONABLE VIEW "APP"."V" AS SELECT 1 FROM dual'],
    );
    expect(plan).toEqual({
      check: [],
      statements: ['CREATE OR REPLACE VIEW "APP"."V" AS SELECT 2 FROM dual'],
      recovery: ['CREATE OR REPLACE FORCE EDITIONABLE VIEW "APP"."V" AS SELECT 1 FROM dual'],
    });
  });

  it('rewrites every statement of a routine or trigger and leaves the rest', () => {
    const plan = oracleDdl.replaceObject(
      { kind: 'trigger', schema: 'APP', name: 'TR', table: 'T' },
      [
        'CREATE TRIGGER "APP"."TR" BEFORE INSERT ON "APP"."T" BEGIN NULL; END;',
        'ALTER TRIGGER "APP"."TR" ENABLE',
      ],
      [
        'CREATE OR REPLACE TRIGGER "APP"."TR" BEFORE UPDATE ON "APP"."T" BEGIN NULL; END;',
        'ALTER TRIGGER "APP"."TR" DISABLE',
      ],
    );
    expect(plan.statements).toEqual([
      'CREATE OR REPLACE TRIGGER "APP"."TR" BEFORE INSERT ON "APP"."T" BEGIN NULL; END;',
      'ALTER TRIGGER "APP"."TR" ENABLE',
    ]);
    expect(plan.recovery).toEqual([
      'CREATE OR REPLACE TRIGGER "APP"."TR" BEFORE UPDATE ON "APP"."T" BEGIN NULL; END;',
      'ALTER TRIGGER "APP"."TR" DISABLE',
    ]);
    for (const kind of ['function', 'procedure'] as const) {
      expect(
        oracleDdl.replaceObject({ kind, name: 'X' }, [`CREATE ${kind} x IS BEGIN NULL; END;`], [])
          .statements,
      ).toEqual([`CREATE OR REPLACE ${kind} x IS BEGIN NULL; END;`]);
    }
  });

  it('drops a materialized view and creates it again, recovering it as it was', () => {
    const plan = oracleDdl.replaceObject(
      { ...view, materialized: true },
      ['CREATE MATERIALIZED VIEW "APP"."V" AS SELECT 1 FROM dual'],
      [
        'CREATE MATERIALIZED VIEW "APP"."V" AS SELECT 0 FROM dual',
        'COMMENT ON MATERIALIZED VIEW "APP"."V" IS \'x\'',
      ],
    );
    expect(plan).toEqual({
      check: [],
      statements: [
        'DROP MATERIALIZED VIEW "APP"."V"',
        'CREATE MATERIALIZED VIEW "APP"."V" AS SELECT 1 FROM dual',
      ],
      recovery: [
        'CREATE MATERIALIZED VIEW "APP"."V" AS SELECT 0 FROM dual',
        'COMMENT ON MATERIALIZED VIEW "APP"."V" IS \'x\'',
      ],
    });
    expect(
      oracleDdl.replaceObject({ kind: 'view', name: 'M', materialized: true }, [], []).statements,
    ).toEqual(['DROP MATERIALIZED VIEW "M"']);
  });

  it('refuses tables, sequences and events', () => {
    for (const kind of ['table', 'sequence', 'event'] as const) {
      expect(() => oracleDdl.replaceObject({ kind, name: 'X' }, ['CREATE x'], [])).toThrow(
        expect.objectContaining({ code: 'unsupported' }),
      );
    }
  });
});
