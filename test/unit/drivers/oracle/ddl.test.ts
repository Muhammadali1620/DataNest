import { describe, expect, it } from 'vitest';
import { DbError } from '../../../../src/core/errors';
import type { ObjectRef } from '../../../../src/core/model/objects';
import { EMPTY_PLAN } from '../../../../src/drivers/driver';
import {
  oracleAlterTable,
  oracleColumnSql,
  oracleDdl,
  oracleKey,
  orReplace,
} from '../../../../src/drivers/oracle/ddl';
import {
  type ForeignKeyDesign,
  NO_BACKGROUND,
  type TableBackground,
  type TableDesign,
} from '../../../../src/shared/table-design';
import { added, column, ordersDesign, withColumn } from '../../../helpers/designs';

const table = { schema: 'APP', name: 'orders' };
const before = ordersDesign();
const target = '"APP"."orders"';

function alter(after: TableDesign, background: TableBackground = NO_BACKGROUND, from = before) {
  return oracleAlterTable(table, from, after, background);
}

function statements(after: TableDesign, background?: TableBackground, from = before) {
  return alter(after, background, from).statements;
}

const key = (overrides: Partial<ForeignKeyDesign> = {}): ForeignKeyDesign => ({
  id: 'k2',
  name: 'fk_x',
  columns: ['customer_id'],
  targetTable: 'customers',
  targetColumns: ['id'],
  onDelete: 'NO ACTION',
  onUpdate: 'NO ACTION',
  ...overrides,
});

describe('oracleKey', () => {
  it('keeps CASCADE and SET NULL on delete', () => {
    expect(oracleKey(key({ onDelete: 'CASCADE' })).onDelete).toBe('CASCADE');
    expect(oracleKey(key({ onDelete: 'SET NULL' })).onDelete).toBe('SET NULL');
  });

  it('turns every other delete rule into NO ACTION', () => {
    expect(oracleKey(key({ onDelete: 'RESTRICT' })).onDelete).toBe('NO ACTION');
    expect(oracleKey(key({ onDelete: 'SET DEFAULT' })).onDelete).toBe('NO ACTION');
    expect(oracleKey(key({ onDelete: 'NO ACTION' })).onDelete).toBe('NO ACTION');
  });

  it('drops ON UPDATE, which Oracle does not have, and keeps the rest', () => {
    const original = key({ onDelete: 'CASCADE', onUpdate: 'CASCADE', targetSchema: 'SALES' });
    expect(oracleKey(original)).toEqual({ ...original, onUpdate: 'NO ACTION' });
    expect(original.onUpdate).toBe('CASCADE');
  });
});

describe('oracleColumnSql', () => {
  it('writes the name, the type with its length and NOT NULL', () => {
    expect(oracleColumnSql(column(' note ', { type: 'VARCHAR2', length: '40 CHAR' }))).toBe(
      '"note" VARCHAR2(40 CHAR)',
    );
    expect(oracleColumnSql(column('n', { type: 'NUMBER', length: '10,2', nullable: false }))).toBe(
      '"n" NUMBER(10,2) NOT NULL',
    );
  });

  it('puts the default before NOT NULL, as Oracle wants it', () => {
    expect(
      oracleColumnSql(
        column('state', {
          type: 'VARCHAR2',
          length: '10',
          defaultValue: " 'new' ",
          nullable: false,
        }),
      ),
    ).toBe('"state" VARCHAR2(10) DEFAULT \'new\' NOT NULL');
    expect(oracleColumnSql(column('at', { type: 'DATE', defaultValue: 'SYSDATE' }))).toBe(
      '"at" DATE DEFAULT SYSDATE',
    );
    expect(oracleColumnSql(column('blank', { defaultValue: '   ' }))).toBe('"blank" int');
  });

  it('makes a key column NOT NULL even when it was ticked nullable', () => {
    expect(oracleColumnSql(column('id', { primaryKey: true, nullable: true }))).toBe(
      '"id" int NOT NULL',
    );
  });

  it('writes an identity column without a default or NOT NULL, which it implies', () => {
    expect(
      oracleColumnSql(
        column('id', {
          type: 'NUMBER',
          autoIncrement: true,
          primaryKey: true,
          nullable: false,
          defaultValue: '0',
        }),
      ),
    ).toBe('"id" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY');
  });

  it('refuses a column name Oracle cannot quote', () => {
    expect(() => oracleColumnSql(column('a"b'))).toThrow(/double quote/u);
  });
});

