import { describe, expect, it } from 'vitest';
import type { ObjectRef } from '../../../../src/core/model/objects';
import { dropIfExists, oracleDump } from '../../../../src/drivers/oracle/dump';

const forgiving = (statement: string, code: number): string =>
  [
    'BEGIN',
    `  EXECUTE IMMEDIATE '${statement.replaceAll("'", "''")}';`,
    'EXCEPTION',
    `  WHEN OTHERS THEN IF SQLCODE <> -${code} THEN RAISE; END IF;`,
    'END;',
  ].join('\n');

describe('dropIfExists', () => {
  it('runs the DROP in PL/SQL and forgives only the missing-object error', () => {
    expect(dropIfExists('DROP TABLE "T"', 942)).toBe(
      [
        'BEGIN',
        `  EXECUTE IMMEDIATE 'DROP TABLE "T"';`,
        'EXCEPTION',
        '  WHEN OTHERS THEN IF SQLCODE <> -942 THEN RAISE; END IF;',
        'END;',
      ].join('\n'),
    );
  });

  it('doubles quotes inside the statement it runs', () => {
    expect(dropIfExists(`DROP VIEW "it's"`, 942)).toContain(
      `EXECUTE IMMEDIATE 'DROP VIEW "it''s"';`,
    );
  });
});

describe('oracleDump', () => {
  it("makes the dumped schema the session's own, so unqualified names in bodies mean it", () => {
    expect(oracleDump.createSchema?.('DATANEST')).toBe(
      'ALTER SESSION SET CURRENT_SCHEMA = "DATANEST"',
    );
    expect(() => oracleDump.createSchema?.('A"B')).toThrow();
  });

  it('reads every table as of one moment and needs no header or footer', () => {
    expect(oracleDump).toMatchObject({
      prepare: [],
      beginSnapshot: ['SET TRANSACTION READ ONLY'],
      endSnapshot: ['COMMIT'],
      header: [],
      footer: [],
      keysAfterData: true,
      routinesFirst: false,
    });
    expect(oracleDump.portable).toBeUndefined();
  });

  it('writes one row as a plain INSERT', () => {
    expect(oracleDump.insert('"APP"."T"', ['"A"', '"B"'], ["(1, 'x')"], false)).toBe(
      `INSERT INTO "APP"."T" ("A", "B") VALUES (1, 'x')`,
    );
    expect(oracleDump.insert('"T"', ['"ID"'], ['(1)'], true)).toBe(
      'INSERT INTO "T" ("ID") VALUES (1)',
    );
  });

  it('writes several rows as INSERTs in one PL/SQL block, so each gets its own identity', () => {
    const expected = [
      'BEGIN',
      `  INSERT INTO "APP"."T" ("A", "B") VALUES (1, 'x');`,
      `  INSERT INTO "APP"."T" ("A", "B") VALUES (2, 'y');`,
      `  INSERT INTO "APP"."T" ("A", "B") VALUES (3, NULL);`,
      'END;',
    ].join('\n');
    const rows = ["(1, 'x')", "(2, 'y')", '(3, NULL)'];
    expect(oracleDump.insert('"APP"."T"', ['"A"', '"B"'], rows, false)).toBe(expected);
    expect(oracleDump.insert('"APP"."T"', ['"A"', '"B"'], rows, true)).toBe(expected);
    expect(oracleDump.insert('"T"', ['"A"'], rows, false)).not.toContain('INSERT ALL');
  });

  it('moves an identity column past the highest value inserted', () => {
    expect(oracleDump.resetSequence?.({ schema: 'APP', name: 'T' }, 'ID')).toBe(
      'ALTER TABLE "APP"."T" MODIFY ("ID" GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE))',
    );
    expect(oracleDump.resetSequence?.({ name: 'T' }, 'id')).toBe(
      'ALTER TABLE "T" MODIFY ("id" GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE))',
    );
  });

  it('drops each table in a block of its own with its constraints, forgiving ORA-00942', () => {
    expect(
      oracleDump.dropRelations([{ name: 'A' }, { schema: 'APP', name: 'B' }], 'table'),
    ).toEqual([
      forgiving('DROP TABLE "A" CASCADE CONSTRAINTS', 942),
      forgiving('DROP TABLE "APP"."B" CASCADE CONSTRAINTS', 942),
    ]);
  });

  it('drops views forgiving ORA-00942 and materialized views forgiving ORA-12003', () => {
    expect(oracleDump.dropRelations([{ schema: 'APP', name: 'V' }], 'view')).toEqual([
      forgiving('DROP VIEW "APP"."V"', 942),
    ]);
    expect(oracleDump.dropRelations([{ schema: 'APP', name: 'M' }], 'materialized-view')).toEqual([
      forgiving('DROP MATERIALIZED VIEW "APP"."M"', 12003),
    ]);
  });

  it('drops nothing for no relations', () => {
    expect(oracleDump.dropRelations([], 'table')).toEqual([]);
  });

  it.each([
    [{ kind: 'table', schema: 'APP', name: 'T' }, 'DROP TABLE "APP"."T"', 942],
    [{ kind: 'view', schema: 'APP', name: 'V' }, 'DROP VIEW "APP"."V"', 942],
    [{ kind: 'function', schema: 'APP', name: 'F' }, 'DROP FUNCTION "APP"."F"', 4043],
    [{ kind: 'procedure', name: 'P' }, 'DROP PROCEDURE "P"', 4043],
    [{ kind: 'trigger', schema: 'APP', name: 'TR', table: 'T' }, 'DROP TRIGGER "APP"."TR"', 4080],
    [{ kind: 'sequence', schema: 'APP', name: 'S' }, 'DROP SEQUENCE "APP"."S"', 2289],
  ] as const)('drops %o with %s, forgiving ORA-%i', (object: ObjectRef, statement, code) => {
    expect(oracleDump.dropObject(object)).toBe(forgiving(statement, code));
  });

  it('forgives only ORA-12003 when a materialized view is missing', () => {
    expect(
      oracleDump.dropObject({ kind: 'view', materialized: true, schema: 'APP', name: 'M' }),
    ).toBe(forgiving('DROP MATERIALIZED VIEW "APP"."M"', 12003));
  });

  it('refuses events, which Oracle keeps in its scheduler', () => {
    expect(() => oracleDump.dropObject({ kind: 'event', name: 'E' })).toThrow(
      expect.objectContaining({ code: 'unsupported' }),
    );
  });
});
