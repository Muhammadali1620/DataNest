import { describe, expect, it } from 'vitest';
import { postgresDialect } from '../../../../src/drivers/postgres/dialect';
import {
  NO_BACKGROUND,
  type TableBackground,
  type TableDesign,
} from '../../../../src/shared/table-design';
import { added, ordersDesign, withColumn } from '../../../helpers/designs';

const table = { schema: 'sales', name: 'orders' };
const before = ordersDesign();

function alter(after: TableDesign, background: TableBackground = NO_BACKGROUND) {
  return postgresDialect.ddl.alterTable(table, before, after, background);
}

/** The statements between BEGIN and COMMIT. */
function body(after: TableDesign, background?: TableBackground): readonly string[] {
  const { statements } = alter(after, background);
  expect(statements[0]).toBe('BEGIN');
  expect(statements.at(-1)).toBe('COMMIT');
  return statements.slice(1, -1);
}

describe('postgres alterTable', () => {
  it('does nothing for an unchanged table', () => {
    expect(alter(structuredClone(before)).statements).toEqual([]);
  });

  it('runs everything in a transaction that is rolled back on failure', () => {
    const plan = alter({ ...before, comment: 'x' });
    expect(plan.recovery).toEqual(['ROLLBACK']);
  });

  it('renames, retypes and changes nullability and default, in that order', () => {
    const after = withColumn(before, 'note', {
      name: 'remark',
      type: 'text',
      length: '',
      nullable: false,
      defaultValue: "''",
    });
    expect(body(after)).toEqual([
      'ALTER TABLE "sales"."orders" RENAME COLUMN "note" TO "remark"',
      'ALTER TABLE "sales"."orders" ALTER COLUMN "remark" TYPE text USING "remark"::text',
      `ALTER TABLE "sales"."orders" ALTER COLUMN "remark" SET DEFAULT ''`,
      'ALTER TABLE "sales"."orders" ALTER COLUMN "remark" SET NOT NULL',
    ]);
  });

  it('drops a default and NOT NULL', () => {
    const from = withColumn(before, 'note', { nullable: false, defaultValue: "'x'" });
    const plan = postgresDialect.ddl.alterTable(table, from, before, NO_BACKGROUND);
    expect(plan.statements.slice(1, -1)).toEqual([
      'ALTER TABLE "sales"."orders" ALTER COLUMN "note" DROP DEFAULT',
      'ALTER TABLE "sales"."orders" ALTER COLUMN "note" DROP NOT NULL',
    ]);
  });

  it('adds and drops identity', () => {
    expect(body(withColumn(before, 'id', { autoIncrement: true }))).toEqual([
      'ALTER TABLE "sales"."orders" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY',
    ]);
    const identity = withColumn(before, 'id', { autoIncrement: true });
    const plan = postgresDialect.ddl.alterTable(table, identity, before, NO_BACKGROUND);
    expect(plan.statements.slice(1, -1)).toEqual([
      'ALTER TABLE "sales"."orders" ALTER COLUMN "id" DROP IDENTITY IF EXISTS',
    ]);
  });

  it('adds columns at the end and says the order on the page is not applied', () => {
    const plan = alter({
      ...before,
      columns: [added('rank', { comment: 'r' }), ...before.columns],
    });
    expect(plan.statements.slice(1, -1)).toEqual([
      'ALTER TABLE "sales"."orders" ADD COLUMN "rank" int',
      `COMMENT ON COLUMN "sales"."orders"."rank" IS 'r'`,
    ]);
    expect(plan.notes).toEqual(['order-ignored']);
    expect(alter({ ...before, columns: [...before.columns, added('rank')] }).notes).toEqual([]);
  });

  it('drops a column, and the key and index on it with IF EXISTS', () => {
    const after: TableDesign = {
      ...before,
      columns: before.columns.filter((c) => c.name !== 'customer_id'),
      foreignKeys: [],
    };
    expect(body(after)).toEqual([
      'ALTER TABLE "sales"."orders" DROP CONSTRAINT IF EXISTS "fk_customer"',
      'ALTER TABLE "sales"."orders" DROP COLUMN "customer_id"',
    ]);
  });

  it('drops a plain index by its schema and a constraint index as a constraint', () => {
    const after = { ...before, indexes: [] };
    expect(body(after)).toEqual(['DROP INDEX IF EXISTS "sales"."ix_note"']);
    expect(body(after, { ...NO_BACKGROUND, constraintIndexes: ['ix_note'] })).toEqual([
      'ALTER TABLE "sales"."orders" DROP CONSTRAINT IF EXISTS "ix_note"',
    ]);
  });

  it('replaces the primary key under its real name', () => {
    const after = withColumn(before, 'customer_id', { primaryKey: true, nullable: false });
    expect(body(after, { ...NO_BACKGROUND, primaryKeyName: 'orders_key' })).toEqual([
      'ALTER TABLE "sales"."orders" DROP CONSTRAINT IF EXISTS "orders_key"',
      'ALTER TABLE "sales"."orders" ALTER COLUMN "customer_id" SET NOT NULL',
      'ALTER TABLE "sales"."orders" ADD PRIMARY KEY ("id", "customer_id")',
    ]);
    // Without a known name, the one PostgreSQL gives by default.
    expect(body(after)[0]).toBe(
      'ALTER TABLE "sales"."orders" DROP CONSTRAINT IF EXISTS "orders_pkey"',
    );
  });

  it('creates new indexes and keys, comments, and renames the table last', () => {
    const after: TableDesign = {
      ...before,
      name: 'purchases',
      comment: '',
      indexes: [
        ...before.indexes,
        { id: 'i2', name: 'uq_customer', columns: ['customer_id'], unique: true },
      ],
      foreignKeys: before.foreignKeys.map((k) => ({ ...k, onUpdate: 'CASCADE' })),
    };
    const from = { ...before, comment: 'old' };
    const plan = postgresDialect.ddl.alterTable(table, from, after, NO_BACKGROUND);
    expect(plan.statements.slice(1, -1)).toEqual([
      'ALTER TABLE "sales"."orders" DROP CONSTRAINT IF EXISTS "fk_customer"',
      'CREATE UNIQUE INDEX "uq_customer" ON "sales"."orders" ("customer_id")',
      'ALTER TABLE "sales"."orders" ADD CONSTRAINT "fk_customer" FOREIGN KEY ("customer_id") REFERENCES "sales"."customers" ("id") ON UPDATE CASCADE',
      'COMMENT ON TABLE "sales"."orders" IS NULL',
      'ALTER TABLE "sales"."orders" RENAME TO "purchases"',
    ]);
  });
});
