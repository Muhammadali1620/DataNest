import { describe, expect, it } from 'vitest';
import { postgresDialect } from '../../../../src/drivers/postgres/dialect';
import {
  type ColumnDesign,
  newTableDesign,
  type TableDesign,
} from '../../../../src/shared/table-design';

function firstColumn(design: TableDesign): ColumnDesign {
  const [column] = design.columns;
  if (column === undefined) {
    throw new Error('The design has no columns');
  }
  return column;
}

const { ddl } = postgresDialect;
const table = { database: 'shop', schema: 'sales', name: 'orders' };

describe('postgres ddl', () => {
  it('creates and drops databases and schemas', () => {
    expect(ddl.createDatabase?.('new"db')).toBe('CREATE DATABASE "new""db"');
    expect(ddl.dropDatabase?.('shop')).toBe('DROP DATABASE "shop"');
    expect(ddl.createSchema?.('sales')).toBe('CREATE SCHEMA "sales"');
    expect(ddl.dropSchema?.('sales', false)).toBe('DROP SCHEMA "sales"');
    expect(ddl.dropSchema?.('sales', true)).toBe('DROP SCHEMA "sales" CASCADE');
  });

  it('uses the words of each relation kind', () => {
    expect(ddl.dropRelation(table, 'table')).toBe('DROP TABLE "sales"."orders"');
    expect(ddl.dropRelation(table, 'view')).toBe('DROP VIEW "sales"."orders"');
    expect(ddl.dropRelation(table, 'materialized-view')).toBe(
      'DROP MATERIALIZED VIEW "sales"."orders"',
    );
    expect(ddl.renameRelation(table, 'materialized-view', 'o2')).toBe(
      'ALTER MATERIALIZED VIEW "sales"."orders" RENAME TO "o2"',
    );
    expect(ddl.renameRelation({ name: 't' }, 'table', 'u')).toBe('ALTER TABLE "t" RENAME TO "u"');
    expect(ddl.truncateTable(table)).toBe('TRUNCATE TABLE "sales"."orders"');
  });

  it('drops routines by signature and triggers on their table', () => {
    expect(
      ddl.dropObject({ schema: 's', kind: 'function', name: 'f', signature: 'a integer' }),
    ).toBe('DROP FUNCTION "s"."f"(a integer)');
    expect(ddl.dropObject({ kind: 'procedure', name: 'p' })).toBe('DROP PROCEDURE "p"()');
    expect(ddl.dropObject({ schema: 's', kind: 'trigger', name: 't', table: 'orders' })).toBe(
      'DROP TRIGGER "t" ON "s"."orders"',
    );
    expect(ddl.dropObject({ schema: 's', kind: 'sequence', name: 'q' })).toBe(
      'DROP SEQUENCE "s"."q"',
    );
    expect(ddl.dropObject({ kind: 'view', name: 'v' })).toBe('DROP VIEW "v"');
  });

  it('cannot drop a trigger without its table, nor an event', () => {
    expect(() => ddl.dropObject({ kind: 'trigger', name: 't' })).toThrow(
      expect.objectContaining({ code: 'unsupported' }),
    );
    expect(() => ddl.dropObject({ kind: 'event', name: 'e' })).toThrow(
      expect.objectContaining({ code: 'unsupported' }),
    );
  });

  describe('createTable', () => {
    it('uses identity and writes comments as statements of their own', () => {
      const design = newTableDesign('postgres', 'orders');
      const statements = ddl.createTable(table, {
        ...design,
        comment: "it's mine",
        columns: [
          { ...firstColumn(design), comment: 'key' },
          {
            id: 'n',
            name: 'placed',
            type: 'timestamp with time zone',
            length: '3',
            nullable: true,
            defaultValue: 'now()',
            autoIncrement: false,
            primaryKey: false,
            comment: '',
          },
        ],
      });
      expect(statements).toEqual([
        [
          'CREATE TABLE "sales"."orders" (',
          '  "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,',
          '  "placed" timestamp(3) with time zone DEFAULT now(),',
          '  PRIMARY KEY ("id")',
          ')',
        ].join('\n'),
        `COMMENT ON TABLE "sales"."orders" IS 'it''s mine'`,
        `COMMENT ON COLUMN "sales"."orders"."id" IS 'key'`,
      ]);
    });

    it('creates a table without a key', () => {
      const design = newTableDesign('postgres', 'log');
      const [sql] = ddl.createTable(
        { name: 'log' },
        {
          ...design,
          columns: [{ ...firstColumn(design), primaryKey: false, autoIncrement: false }],
        },
      );
      expect(sql).toBe('CREATE TABLE "log" (\n  "id" integer NOT NULL\n)');
    });
  });

  describe('createTable with indexes and keys', () => {
    const partsDesign = (base: TableDesign): TableDesign => ({
      ...base,
      columns: [
        ...base.columns,
        {
          id: 'p',
          name: 'parent_id',
          type: 'integer',
          length: '',
          nullable: true,
          defaultValue: '',
          autoIncrement: false,
          primaryKey: false,
          comment: '',
        },
      ],
      indexes: [
        { id: 'i1', name: 'ix_parent', columns: ['p'], unique: false },
        { id: 'i2', name: 'uq_both', columns: ['new-1', 'p'], unique: true },
      ],
      foreignKeys: [
        {
          id: 'k1',
          name: 'fk_parent',
          columns: ['p'],
          targetTable: 'parents',
          targetColumns: ['id'],
          onDelete: 'CASCADE',
          onUpdate: 'NO ACTION',
        },
      ],
    });

    it('keeps keys inside and creates indexes after the table', () => {
      const statements = ddl.createTable(table, partsDesign(newTableDesign('postgres', 'orders')));
      expect(statements[0]).toContain(
        '  CONSTRAINT "fk_parent" FOREIGN KEY ("parent_id") REFERENCES "sales"."parents" ("id") ON DELETE CASCADE\n)',
      );
      expect(statements.slice(1)).toEqual([
        'CREATE INDEX "ix_parent" ON "sales"."orders" ("parent_id")',
        'CREATE UNIQUE INDEX "uq_both" ON "sales"."orders" ("id", "parent_id")',
      ]);
    });

    it('lets a key point into another schema', () => {
      const design = partsDesign(newTableDesign('postgres', 'orders'));
      const [sql] = ddl.createTable(table, {
        ...design,
        foreignKeys: design.foreignKeys.map((key) => ({ ...key, targetSchema: 'public' })),
      });
      expect(sql).toContain('REFERENCES "public"."parents" ("id")');
    });
  });
});
