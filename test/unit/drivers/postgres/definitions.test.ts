import { describe, expect, it } from 'vitest';
import { readPgDefinition } from '../../../../src/drivers/postgres/definitions';

/**
 * A catalog that answers by the first words of each query, the way the reader asks:
 * the relation, its columns, constraints, indexes, column comments, triggers.
 */
function catalog(answers: Record<string, unknown[][]>) {
  const asked: { sql: string; params: unknown[] | undefined }[] = [];
  const read = (sql: string, params?: unknown[]) => {
    asked.push({ sql, params });
    const key = Object.keys(answers).find((prefix) => sql.includes(prefix));
    return Promise.resolve(key === undefined ? [] : (answers[key] ?? []));
  };
  return { read, asked };
}

const RELATION = 'obj_description(c.oid';
const COLUMNS = 'format_type(a.atttypid';
const CONSTRAINTS = 'pg_get_constraintdef';
const INDEXES = 'pg_get_indexdef';
const COLUMN_COMMENTS = 'col_description(a.attrelid, a.attnum)\n';
const TRIGGERS = 'pg_get_triggerdef(oid';

describe('readPgDefinition: tables', () => {
  it('frames columns and constraints and appends indexes, comments and triggers', async () => {
    const { read } = catalog({
      [RELATION]: [['42', 'r', 'p', 'Shop customers', null, null]],
      [COLUMNS]: [
        ['id', 'integer', true, null, 'a', '', null],
        ['email', 'text', true, null, '', '', 'pg_catalog."C"'],
        ['score', 'numeric(5,2)', false, '0', '', '', null],
        ['code', 'text', false, 'upper(email)', '', 's', null],
        ['seq', 'bigint', true, null, 'd', '', null],
      ],
      [CONSTRAINTS]: [['customers_pkey', 'PRIMARY KEY (id)']],
      [INDEXES]: [['CREATE INDEX ix ON public.customers USING btree (email)']],
      [COLUMN_COMMENTS]: [['email', "it's the login"]],
      [TRIGGERS]: [
        ['CREATE TRIGGER t BEFORE INSERT ON customers FOR EACH ROW EXECUTE FUNCTION f()'],
      ],
    });
    const statements = await readPgDefinition(read, { kind: 'table', name: 'customers' });
    expect(statements).toEqual([
      [
        'CREATE TABLE "public"."customers" (',
        '  "id" integer GENERATED ALWAYS AS IDENTITY NOT NULL,',
        '  "email" text COLLATE pg_catalog."C" NOT NULL,',
        '  "score" numeric(5,2) DEFAULT 0,',
        '  "code" text GENERATED ALWAYS AS (upper(email)) STORED,',
        '  "seq" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,',
        '  CONSTRAINT "customers_pkey" PRIMARY KEY (id)',
        ')',
      ].join('\n'),
      'CREATE INDEX ix ON public.customers USING btree (email)',
      `COMMENT ON TABLE "public"."customers" IS 'Shop customers'`,
      `COMMENT ON COLUMN "public"."customers"."email" IS 'it''s the login'`,
      'CREATE TRIGGER t BEFORE INSERT ON customers FOR EACH ROW EXECUTE FUNCTION f()',
    ]);
  });

  it('marks unlogged and partitioned tables', async () => {
    const { read } = catalog({
      [RELATION]: [['7', 'p', 'u', null, null, 'RANGE (created)']],
      [COLUMNS]: [['created', 'date', true, null, '', '', null]],
    });
    const [table] = await readPgDefinition(read, { schema: 'logs', kind: 'table', name: 'ev' });
    expect(table).toBe(
      'CREATE UNLOGGED TABLE "logs"."ev" (\n  "created" date NOT NULL\n) PARTITION BY RANGE (created)',
    );
  });

  it('writes a virtual generated column (PostgreSQL 18)', async () => {
    const { read } = catalog({
      [RELATION]: [['7', 'r', 'p', null, null, null]],
      [COLUMNS]: [['v', 'integer', false, 'a + 1', '', 'v', null]],
    });
    const [table] = await readPgDefinition(read, { kind: 'table', name: 't' });
    expect(table).toContain('"v" integer GENERATED ALWAYS AS (a + 1) VIRTUAL');
  });

  it('asks the catalogs with the schema and name as parameters', async () => {
    const { read, asked } = catalog({});
    await expect(
      readPgDefinition(read, { schema: "x'; DROP", kind: 'table', name: 't' }),
    ).rejects.toMatchObject({ code: 'not-found', message: "x'; DROP.t does not exist" });
    expect(asked[0]?.params).toEqual(["x'; DROP", 't']);
  });
});

describe('readPgDefinition: views', () => {
  it('writes CREATE OR REPLACE VIEW without the trailing semicolon of the catalog', async () => {
    const { read } = catalog({
      [RELATION]: [['9', 'v', 'p', 'totals', ' SELECT 1 AS one;', null]],
    });
    expect(await readPgDefinition(read, { kind: 'view', name: 'v' })).toEqual([
      'CREATE OR REPLACE VIEW "public"."v" AS\nSELECT 1 AS one',
      `COMMENT ON VIEW "public"."v" IS 'totals'`,
    ]);
  });

  it('writes a materialized view with its indexes', async () => {
    const { read } = catalog({
      [RELATION]: [['9', 'm', 'p', null, ' SELECT 2;', null]],
      [INDEXES]: [['CREATE INDEX mi ON public.mv USING btree (x)']],
    });
    expect(await readPgDefinition(read, { kind: 'view', name: 'mv' })).toEqual([
      'CREATE MATERIALIZED VIEW "public"."mv" AS\nSELECT 2',
      'CREATE INDEX mi ON public.mv USING btree (x)',
    ]);
  });
});

describe('readPgDefinition: routines, triggers, sequences', () => {
  it('returns each overload with its comment', async () => {
    const { read, asked } = catalog({
      'pg_get_functiondef(p.oid)': [
        ['CREATE OR REPLACE FUNCTION public.f(a integer)\n RETURNS int\n', 'adds', 'a integer'],
        ['CREATE OR REPLACE FUNCTION public.f(a text)\n RETURNS int\n', null, 'a text'],
      ],
    });
    expect(await readPgDefinition(read, { kind: 'function', name: 'f' })).toEqual([
      'CREATE OR REPLACE FUNCTION public.f(a integer)\n RETURNS int',
      `COMMENT ON FUNCTION "public"."f"(a integer) IS 'adds'`,
      'CREATE OR REPLACE FUNCTION public.f(a text)\n RETURNS int',
    ]);
    expect(asked[0]?.params).toEqual(['public', 'f', 'f', null]);
  });

  it('asks for a procedure and for one signature', async () => {
    const { read, asked } = catalog({
      'pg_get_functiondef(p.oid)': [['CREATE OR REPLACE PROCEDURE public.p()', null, '']],
    });
    await readPgDefinition(read, { kind: 'procedure', name: 'p', signature: '' });
    expect(asked[0]?.params).toEqual(['public', 'p', 'p', '']);
  });

  it('says not-found for a missing routine, trigger or sequence', async () => {
    const { read } = catalog({});
    for (const kind of ['function', 'procedure', 'trigger', 'sequence'] as const) {
      await expect(readPgDefinition(read, { kind, name: 'x' })).rejects.toMatchObject({
        code: 'not-found',
      });
    }
  });

  it('filters a trigger by its table when known', async () => {
    const { read, asked } = catalog({ 'pg_get_triggerdef(t.oid': [['CREATE TRIGGER t']] });
    expect(await readPgDefinition(read, { kind: 'trigger', name: 't', table: 'orders' })).toEqual([
      'CREATE TRIGGER t',
    ]);
    expect(asked[0]?.params).toEqual(['public', 't', 'orders']);
  });

  it('writes a sequence with every option and its owner', async () => {
    const { read } = catalog({
      'FROM pg_sequence s': [['bigint', '1', '1', '99', '10', '1', true, 'public.t.id']],
    });
    expect(await readPgDefinition(read, { kind: 'sequence', name: 's' })).toEqual([
      [
        'CREATE SEQUENCE "public"."s"',
        '  AS bigint',
        '  INCREMENT BY 1',
        '  MINVALUE 1',
        '  MAXVALUE 99',
        '  START WITH 10',
        '  CACHE 1',
        '  CYCLE',
      ].join('\n'),
      'ALTER SEQUENCE "public"."s" OWNED BY public.t.id',
    ]);
  });

  it('has no events', async () => {
    await expect(
      readPgDefinition(catalog({}).read, { kind: 'event', name: 'e' }),
    ).rejects.toMatchObject({ code: 'unsupported' });
  });
});

describe('readPgDefinition on PostgreSQL-compatible servers (V6.5)', () => {
  function withServer<T extends (...args: never[]) => unknown>(
    read: T,
    server: { flavor: 'postgres' | 'cockroach' | 'yugabyte'; version: number },
  ) {
    return Object.assign(read, { server });
  }

  it('reads no generated columns before PostgreSQL 12 (YugabyteDB is 11)', async () => {
    const { read, asked } = catalog({
      [RELATION]: [['42', 'r', 'p', null, null, null]],
      [COLUMNS]: [['id', 'integer', true, null, '', '', null]],
    });
    await readPgDefinition(withServer(read, { flavor: 'yugabyte', version: 110_002 }), {
      kind: 'table',
      name: 't',
    });
    const columns = asked.find((question) => question.sql.includes(COLUMNS))?.sql ?? '';
    expect(columns).not.toContain('attgenerated');
    expect(columns).toContain("''::text");
  });

  it('leaves out the triggers CockroachDB cannot print, and refuses a trigger alone', async () => {
    const { read, asked } = catalog({
      [RELATION]: [['42', 'r', 'p', null, null, null]],
      [COLUMNS]: [['id', 'integer', true, null, '', '', null]],
    });
    const cockroach = withServer(read, { flavor: 'cockroach', version: 130_000 });
    const statements = await readPgDefinition(cockroach, { kind: 'table', name: 't' });
    expect(statements).toHaveLength(1);
    expect(asked.some((question) => question.sql.includes('pg_get_triggerdef'))).toBe(false);
    await expect(
      readPgDefinition(cockroach, { kind: 'trigger', name: 'tr', table: 't' }),
    ).rejects.toMatchObject({ code: 'unsupported' });
  });

  it("writes a CockroachDB view without its own database's name", async () => {
    const { read } = catalog({
      [RELATION]: [['7', 'v', 'p', null, 'SELECT id FROM shop.public.orders;', null, 'shop']],
    });
    expect(
      await readPgDefinition(withServer(read, { flavor: 'cockroach', version: 130_000 }), {
        kind: 'view',
        name: 'v',
      }),
    ).toEqual(['CREATE OR REPLACE VIEW "public"."v" AS\nSELECT id FROM public.orders']);
  });
});
