import { describe, expect, it } from 'vitest';
import type { TableStructure } from '../../../../src/core/model/objects';
import type { Driver, Session } from '../../../../src/drivers/driver';
import { mysqlDialect } from '../../../../src/drivers/mysql/dialect';
import { postgresDialect } from '../../../../src/drivers/postgres/dialect';
import {
  type TransferRequest,
  TableTransferService,
} from '../../../../src/services/transfer/table-transfer';
import { FakeDriver, FakeSession } from '../../../helpers/fake-driver';
import { RecordingLogger } from '../../../helpers/fakes';

const ORDERS: TableStructure = {
  columns: [
    { name: 'id', dataType: 'int', nullable: false, autoIncrement: true, generated: false },
    {
      name: 'customer_id',
      dataType: 'int',
      nullable: false,
      autoIncrement: false,
      generated: false,
    },
    {
      name: 'paid',
      dataType: 'tinyint(1)',
      nullable: false,
      autoIncrement: false,
      generated: false,
      defaultExpression: '0',
    },
    {
      name: 'made_at',
      dataType: 'datetime',
      nullable: true,
      autoIncrement: false,
      generated: false,
      defaultExpression: 'uuid()',
    },
    { name: 'twice', dataType: 'int', nullable: true, autoIncrement: false, generated: true },
  ],
  primaryKey: ['id'],
  indexes: [{ name: 'ix_customer', columns: ['customer_id'], unique: false, primary: false }],
  foreignKeys: [
    {
      name: 'fk_customer',
      columns: ['customer_id'],
      target: { database: 'shop', name: 'customers' },
      targetColumns: ['id'],
    },
    {
      name: 'fk_elsewhere',
      columns: ['customer_id'],
      target: { database: 'shop', name: 'not_copied' },
      targetColumns: ['id'],
    },
  ],
};

class Harness {
  readonly fromDriver: FakeDriver;
  readonly toDriver: FakeDriver;
  readonly reader = new FakeSession({ id: 'a', name: 'a', driver: 'mysql' });
  readonly writer = new FakeSession({ id: 'b', name: 'b', driver: 'postgres' });
  readonly released: string[] = [];

  constructor(from: 'mysql' | 'postgres' = 'mysql', to: 'mysql' | 'postgres' = 'postgres') {
    this.fromDriver = new FakeDriver(from);
    this.toDriver = new FakeDriver(to);
    this.fromDriver.dialect = from === 'mysql' ? mysqlDialect : postgresDialect;
    this.toDriver.dialect = to === 'mysql' ? mysqlDialect : postgresDialect;
    this.reader.metadata.structure = ORDERS;
    this.reader.rowsFor = (sql) =>
      sql.startsWith('SELECT `id`')
        ? [
            [1, 7, 1, '2024-01-01 10:00:00'],
            [2, 7, 0, null],
          ]
        : [];
    this.writer.metadata.tables = [];
  }

  service(): TableTransferService {
    return new TableTransferService({
      manager: {
        driverOf: (connectionId) =>
          Promise.resolve((connectionId === 'from' ? this.fromDriver : this.toDriver) as Driver),
        acquire: (_owner, target) =>
          Promise.resolve((target.connectionId === 'from' ? this.reader : this.writer) as Session),
        release: (owner) => {
          this.released.push(owner);
          return Promise.resolve();
        },
      },
      logger: new RecordingLogger(),
      now: () => 0,
    });
  }

  async run(overrides: Partial<TransferRequest> = {}) {
    return await this.service().transfer({
      source: { target: { connectionId: 'from', database: 'shop' }, scope: { database: 'shop' } },
      destination: { target: { connectionId: 'to' }, scope: { schema: 'public' } },
      tables: ['customers', 'orders'],
      content: 'all',
      existing: 'replace',
      ...overrides,
    });
  }

  /** Statements the target ran, in order, by their first words. */
  steps(): string[] {
    return this.writer.executed.map((sql) => sql.split(/\s+/u).slice(0, 3).join(' '));
  }
}

describe('TableTransferService', () => {
  it('reads in a snapshot, creates, fills, then adds keys on PostgreSQL', async () => {
    const harness = new Harness();
    const report = await harness.run();
    expect(harness.reader.executed.slice(0, 3)).toEqual([
      "SET time_zone = '+00:00'",
      'SET SESSION TRANSACTION ISOLATION LEVEL REPEATABLE READ',
      'START TRANSACTION WITH CONSISTENT SNAPSHOT, READ ONLY',
    ]);
    expect(harness.reader.executed.at(-1)).toBe('ROLLBACK');
    const sql = harness.writer.executed.join('\n');
    expect(sql).toContain('CREATE TABLE "public"."orders"');
    expect(sql).toContain('"id" integer GENERATED BY DEFAULT AS IDENTITY');
    expect(sql).toContain('"paid" boolean NOT NULL DEFAULT FALSE');
    expect(sql).not.toContain('twice');
    const creates = harness.writer.executed.filter((s) => s.startsWith('CREATE TABLE'));
    expect(creates.every((s) => !s.includes('FOREIGN KEY'))).toBe(true);
    expect(sql).toContain(
      'INSERT INTO "public"."orders" ("id", "customer_id", "paid", "made_at") OVERRIDING SYSTEM VALUE VALUES\n(1, 7, TRUE, \'2024-01-01 10:00:00\'),\n(2, 7, FALSE, NULL)',
    );
    const steps = harness.steps();
    const lastInsert = steps.lastIndexOf('INSERT INTO "public"."orders"');
    const alter = steps.findIndex((step) => step.startsWith('ALTER TABLE'));
    expect(alter).toBeGreaterThan(lastInsert);
    expect(harness.writer.executed[alter]).toContain(
      'FOREIGN KEY ("customer_id") REFERENCES "public"."customers"',
    );
    // Constraint and index names belong to the schema in PostgreSQL: they get the table.
    expect(sql).toContain('ADD CONSTRAINT "orders_fk_customer" FOREIGN KEY');
    expect(sql).toContain('CREATE INDEX "orders_ix_customer"');
    expect(harness.writer.executed.at(-1)).toBe('RESET client_min_messages');
    const orders = report.tables.find((table) => table.table === 'orders');
    expect(orders).toMatchObject({ outcome: 'copied', created: true, rows: 2 });
    expect(orders?.notes).toEqual(
      expect.arrayContaining([
        { kind: 'generated-skipped', column: 'twice' },
        { kind: 'default-dropped', column: 'made_at', expression: 'uuid()' },
        { kind: 'key-dropped', key: 'fk_elsewhere', target: 'not_copied' },
      ]),
    );
    expect(harness.released.sort()).toEqual([
      expect.stringMatching(/^task:transfer-\d+-read$/u),
      expect.stringMatching(/^task:transfer-\d+-write$/u),
    ]);
    expect(report.outcome).toBe('done');
    expect(report.rows).toBe(4);
  });

  it('keeps keys inside CREATE TABLE where the target turns checks off (MySQL)', async () => {
    const harness = new Harness('mysql', 'mysql');
    harness.reader.rowsFor = () => [];
    await harness.service().transfer({
      source: { target: { connectionId: 'from' }, scope: { database: 'shop' } },
      destination: { target: { connectionId: 'to' }, scope: {} },
      tables: ['customers', 'orders'],
      content: 'structure',
      existing: 'replace',
    });
    const sql = harness.writer.executed.join('\n');
    expect(sql).toContain(
      'SET @OLD_FOREIGN_KEY_CHECKS = @@FOREIGN_KEY_CHECKS, FOREIGN_KEY_CHECKS = 0',
    );
    expect(sql).toMatch(
      /CREATE TABLE `orders`[\s\S]*FOREIGN KEY \(`customer_id`\) REFERENCES `customers`/u,
    );
    expect(sql).not.toContain('ALTER TABLE');
    expect(sql).not.toContain('INSERT');
  });

  it('drops and creates a table that is there, or leaves it, or adds to it', async () => {
    const replace = new Harness();
    replace.writer.metadata.tables = [{ name: 'orders', kind: 'table' }];
    await replace.run({ tables: ['orders'] });
    expect(replace.writer.executed).toContain('DROP TABLE IF EXISTS "public"."orders"');

    const skip = new Harness();
    skip.writer.metadata.tables = [{ name: 'ORDERS', kind: 'table' }];
    const skipped = await skip.run({ tables: ['orders'], existing: 'skip' });
    expect(skipped.tables).toEqual([
      { table: 'orders', outcome: 'skipped', created: false, rows: 0, notes: [] },
    ]);
    expect(skip.writer.executed.some((sql) => sql.startsWith('INSERT'))).toBe(false);

    const append = new Harness();
    append.writer.metadata.tables = [{ name: 'orders', kind: 'table' }];
    append.writer.metadata.structure = {
      ...ORDERS,
      columns: ORDERS.columns.filter((column) => column.name !== 'made_at'),
    };
    const appended = await append.run({ tables: ['orders'], existing: 'append' });
    expect(appended.tables[0]).toMatchObject({ outcome: 'copied', created: false, rows: 2 });
    expect(appended.tables[0]?.notes).toContainEqual({
      kind: 'columns-skipped',
      columns: ['made_at'],
    });
    expect(append.writer.executed.some((sql) => sql.startsWith('CREATE TABLE'))).toBe(false);
    expect(append.writer.executed.join('\n')).toContain('("id", "customer_id", "paid") OVERRIDING');
  });

  it('reports a table that is missing for a data-only copy', async () => {
    const harness = new Harness();
    const report = await harness.run({ tables: ['orders'], content: 'data' });
    expect(report.tables[0]).toMatchObject({ outcome: 'failed', created: false });
    expect(report.tables[0]?.error).toMatch(/does not exist on the target/u);
  });

  it('goes on with the next table when one fails', async () => {
    const harness = new Harness();
    harness.writer.failExecuteWhen = (sql) => sql.startsWith('INSERT INTO "public"."customers"');
    const report = await harness.run();
    expect(report.tables.map((table) => [table.table, table.outcome])).toEqual([
      ['customers', 'failed'],
      ['orders', 'copied'],
    ]);
    expect(report.tables[0]?.error).toMatch(/Not allowed/u);
  });

  it('stops when cancelled and still lets both sessions go', async () => {
    const harness = new Harness();
    const abort = new AbortController();
    const report = await harness.run({
      signal: abort.signal,
      onProgress: () => {
        abort.abort();
      },
    });
    expect(report.outcome).toBe('cancelled');
    expect(report.tables).toHaveLength(1);
    expect(harness.released).toHaveLength(2);
    expect(harness.writer.executed.some((sql) => sql.startsWith('ALTER TABLE'))).toBe(false);
  });

  it('reports progress per table', async () => {
    const harness = new Harness();
    const seen: unknown[] = [];
    await harness.run({ onProgress: (progress) => seen.push(progress) });
    expect(seen).toEqual([
      { table: 'customers', rows: 2, tablesDone: 0, tablesTotal: 2 },
      { table: 'orders', rows: 4, tablesDone: 1, tablesTotal: 2 },
    ]);
  });
});
