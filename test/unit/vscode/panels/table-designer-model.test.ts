import { describe, expect, it, vi } from 'vitest';
import { mysqlDialect } from '../../../../src/drivers/mysql/dialect';
import { postgresDialect } from '../../../../src/drivers/postgres/dialect';
import { sqliteDialect } from '../../../../src/drivers/sqlite/dialect';
import type { SchemaAction } from '../../../../src/services/schema-actions';
import type { DriverId } from '../../../../src/shared/connection';
import { newTableDesign } from '../../../../src/shared/table-design';
import { TableDesignerModel } from '../../../../src/vscode/panels/table-designer-model';
import type { PerformOutcome } from '../../../../src/vscode/tree/schema-commands';

const DIALECTS = { mysql: mysqlDialect, postgres: postgresDialect, sqlite: sqliteDialect };

function model(driver: DriverId, scope = {}, outcome: PerformOutcome = 'ran') {
  const perform = vi.fn(
    (_connectionId: string, _action: SchemaAction, _title: string, _label: string) =>
      Promise.resolve(outcome),
  );
  const instance = new TableDesignerModel({
    connectionId: 'c1',
    scope,
    driver: { id: driver, dialect: DIALECTS[driver] },
    texts: { createTable: (name) => `create ${name}?`, create: 'Create' },
    perform,
  });
  return { instance, perform };
}

describe('TableDesignerModel', () => {
  it('labels the scope for the title', () => {
    expect(model('postgres', { database: 'shop', schema: 'sales' }).instance.scopeLabel).toBe(
      'shop.sales',
    );
    expect(model('mysql', { database: 'shop' }).instance.scopeLabel).toBe('shop');
    expect(model('sqlite').instance.scopeLabel).toBe('');
  });

  it('starts a new table with the driver features and the default key', () => {
    const state = model('sqlite').instance.state();
    expect(state).toMatchObject({
      mode: 'create',
      driver: 'sqlite',
      scope: '',
      features: { columnComments: false, tableComment: false },
      design: newTableDesign('sqlite'),
    });
    expect(state.features.types).toContain('integer');
  });

  it('previews the SQL of a valid design in its scope', () => {
    const { instance } = model('postgres', { database: 'shop', schema: 'sales' });
    expect(instance.preview(newTableDesign('postgres', ' orders '))).toEqual({
      statements: [
        'CREATE TABLE "sales"."orders" (\n  "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n  PRIMARY KEY ("id")\n)',
      ],
    });
  });

  it('previews nothing while the design has problems', () => {
    expect(model('mysql').instance.preview(newTableDesign('mysql', ''))).toEqual({
      statements: [],
    });
  });

  it('saves through the performer with a create action and the right title', async () => {
    const { instance, perform } = model('mysql', { database: 'shop' });
    const design = newTableDesign('mysql', 'orders');
    expect(await instance.save(design)).toEqual({ outcome: 'ran' });
    expect(perform).toHaveBeenCalledWith(
      'c1',
      { kind: 'createTable', table: { database: 'shop', name: 'orders' }, design },
      'create orders?',
      'Create',
    );
  });

  it('passes the outcome of the dialog back to the page', async () => {
    const { instance } = model('mysql', {}, 'cancelled');
    expect(await instance.save(newTableDesign('mysql', 't'))).toEqual({ outcome: 'cancelled' });
  });

  it('refuses an invalid design without asking anything', async () => {
    const { instance, perform } = model('sqlite');
    const design = newTableDesign('sqlite', 't');
    // AUTOINCREMENT on a text column cannot be saved in SQLite.
    const broken = {
      ...design,
      columns: design.columns.map((column) => ({ ...column, type: 'text' })),
    };
    expect(await instance.save(broken)).toEqual({ outcome: 'invalid' });
    expect(perform).not.toHaveBeenCalled();
  });
});
